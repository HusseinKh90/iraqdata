_DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")


def _is_date(value: Any) -> bool:
    if hasattr(value, "isoformat") and not isinstance(value, str):
        return True
    if not (isinstance(value, str) and _DATE_RE.match(value)):
        return False
    try:
        pd.Timestamp(value)
        return True
    except ValueError:
        return False


def load_update_schedule(path: Union[Path, str] = UPDATE_SCHEDULE_PATH) -> dict:
    """
    Load `update_schedule.yaml`. Raises ValueError
    naming the offending source or series.
    """
    with open(path, "r", encoding="utf-8") as f:
        data = yaml.safe_load(f) or {}
    sources = data.get("sources")
    series = data.get("series")
    if not isinstance(sources, list) or not isinstance(series, dict):
        raise ValueError(f"{path}: needs a 'sources' list and a 'series' mapping")

    import run_parsers  # lazy: the runner pulls in the parser registry

    ids = set()
    for i, src in enumerate(sources):
        sid = src.get("id") if isinstance(src, dict) else None
        name = sid or f"#{i}"
        if not isinstance(src, dict):
            raise ValueError(f"source {name}: must be a mapping")
        for field in ("id", "publisher", "url", "fetch", "parsers", "calendar"):
            if not src.get(field):
                raise ValueError(f"source {name}: missing or empty {field!r}")
        if sid in ids:
            raise ValueError(f"source {name}: duplicate id")
        ids.add(sid)
        if src["fetch"] not in ("auto", "manual"):
            raise ValueError(f"source {name}: fetch must be 'auto' or 'manual', not {src['fetch']!r}")
        if src["fetch"] == "manual" and not src.get("reason"):
            raise ValueError(f"source {name}: a manual source needs a 'reason'")
        if src["fetch"] == "auto" and "reason" in src:
            raise ValueError(f"source {name}: 'reason' is only for manual sources")
        unknown = [p for p in src["parsers"] if p not in run_parsers.BY_NAME]
        if not isinstance(src["parsers"], list) or unknown:
            raise ValueError(f"source {name}: unknown parser(s) {unknown}")
        # What an auto source publishes, and its failure threshold
        if src["fetch"] == "auto" and src.get("kind") not in SOURCE_KINDS:
            raise ValueError(f"source {name}: kind must be one of {list(SOURCE_KINDS)}, not {src.get('kind')!r}")
        threshold = src.setdefault("failure_threshold", DEFAULT_FAILURE_THRESHOLD)
        if isinstance(threshold, bool) or not isinstance(threshold, int) or threshold < 1:
            raise ValueError(f"source {name}: failure_threshold must be an integer >= 1, not {threshold!r}")
        waiting = src.setdefault("pending_threshold", DEFAULT_PENDING_THRESHOLD)
        if isinstance(waiting, bool) or not isinstance(waiting, int) or waiting < 1:
            raise ValueError(f"source {name}: pending_threshold must be an integer >= 1, not {waiting!r}")

    large = data.setdefault("large_revision_pct", DEFAULT_LARGE_REVISION_PCT)
    if isinstance(large, bool) or not isinstance(large, (int, float)) or large <= 0:
        raise ValueError(f"{path}: large_revision_pct must be a number > 0, not {large!r}")

    notify = data.get("notify")
    if not isinstance(notify, dict) or not isinstance(notify.get("github"), str) or not notify["github"].strip():
        raise ValueError(f"{path}: notify.github (the maintainer's GitHub handle) is required")

    covered = {p for src in sources for p in src["parsers"]}
    uncovered = sorted(set(run_parsers.BY_NAME) - covered)
    if uncovered:
        raise ValueError(f"parser(s) {uncovered} belong to no source")

    import fetchers  # lazy: fetchers pull in the CBI downloaders

    no_fetcher = sorted(s["id"] for s in sources if s["fetch"] == "auto" and s["id"] not in fetchers.FETCHERS)
    if no_fetcher:
        raise ValueError(f"auto source(s) {no_fetcher} have no fetcher in pipeline/fetchers.py")

    for sid, rule in series.items():
        if not isinstance(rule, dict):
            raise ValueError(f"series {sid}: must be a mapping")
        if rule.get("source") not in ids:
            raise ValueError(f"series {sid}: unknown source {rule.get('source')!r}")
        if not _is_date(rule.get("reviewed")):
            raise ValueError(f"series {sid}: 'reviewed' must be YYYY-MM-DD")
        has_lag, has_end = "lag_days" in rule, "ended" in rule
        if has_lag == has_end:
            raise ValueError(f"series {sid}: needs exactly one of 'lag_days' or 'ended'")
        if has_lag:
            lag = rule["lag_days"]
            if isinstance(lag, bool) or not isinstance(lag, int) or lag < 1:
                raise ValueError(f"series {sid}: lag_days must be an integer >= 1")
            if not rule.get("rationale"):
                raise ValueError(f"series {sid}: lag_days needs a 'rationale'")
        elif not rule.get("ended"):
            raise ValueError(f"series {sid}: 'ended' needs a reason")
    return data


class FreshnessStatus(NamedTuple):
    dataset: str
    series_id: str
    latest: str
    due: Optional[str]
    days_overdue: int
    state: str          # current | overdue | acknowledged | ended | unchecked
    reason: str
    ack_index: Optional[int]


def production_tables() -> set:
    """Names of the production tables (garden), the only ones judged for freshness."""
    return {p.stem for p in GARDEN_DIR.glob("*.parquet")}


def freshness_status(
    tables: Dict[str, pd.DataFrame],
    schedule: dict,
    acks: List[dict],
    as_of,
    production: Optional[set] = None,
) -> List[FreshnessStatus]:
    """
    Freshness of every series in the production tables at reference date `as_of`
   . Seed snapshots and other tables are skipped.
    """
    if production is None:
        production = production_tables()
    as_of = pd.Timestamp(as_of).normalize()
    rules = schedule.get("series", {})
    out: List[FreshnessStatus] = []
    for dataset in sorted(n for n in tables if n in production):
        df = tables[dataset]
        for sid, latest in sorted(df.groupby("series_id")["date"].max().items()):
            latest = str(latest)
            rule = rules.get(sid)
            if rule is None:
                out.append(FreshnessStatus(dataset, sid, latest, None, 0, "unchecked", "no freshness rule", None))
                continue
            if "ended" in rule:
                out.append(FreshnessStatus(dataset, sid, latest, None, 0, "ended", str(rule["ended"]), None))
                continue
            due = period_end(next_period(latest)) + pd.Timedelta(days=int(rule["lag_days"]))
            if as_of <= due:
                out.append(FreshnessStatus(dataset, sid, latest, due.strftime("%Y-%m-%d"), 0, "current", "", None))
                continue
            days = int((as_of - due).days)
            matches = [i for i, a in enumerate(acks)
                       if a.get("check") == "overdue" and a.get("series") == sid
                       and [str(p) for p in a.get("periods", [])] == [latest]
                       and (not a.get("dataset") or a.get("dataset") == dataset)]
            live = [i for i in matches if not _expired(acks[i], as_of)]
            if live:
                state, reason, ack_i = "acknowledged", acks[live[0]]["reason"], live[0]
            else:
                # An expired acknowledgement no longer applies; its index is kept for [EXPIRED]
                state, reason, ack_i = "overdue", "", (matches[0] if matches else None)
            out.append(FreshnessStatus(dataset, sid, latest, due.strftime("%Y-%m-%d"), days, state, reason, ack_i))
    return out


def freshness_lines(statuses: List[FreshnessStatus], as_of) -> List[str]:
    """The [FRESHNESS] summary line and one line per series that is not current."""
    counts = {s: 0 for s in ("current", "overdue", "acknowledged", "ended", "unchecked")}
    for st in statuses:
        counts[st.state] += 1
    lines = [
        f"[FRESHNESS] as of {pd.Timestamp(as_of).strftime('%Y-%m-%d')}: {counts['current']} current, "
        f"{counts['overdue']} overdue, {counts['acknowledged']} acknowledged, {counts['ended']} ended, "
        f"{counts['unchecked']} unchecked"
    ]
    for st in statuses:
        name = f"{st.dataset}/{st.series_id}"
        late = f"latest {st.latest}, next due {st.due}, {st.days_overdue} days overdue"
        if st.state == "overdue":
            lines.append(f"    [OVERDUE] {name}: {late}")
        elif st.state == "acknowledged":
            lines.append(f"    [ACKNOWLEDGED] {name}: {late} — {st.reason}")
        elif st.state == "ended":
            lines.append(f"    [ENDED] {name}: latest {st.latest} ({st.reason})")
        elif st.state == "unchecked":
            lines.append(f"    [UNCHECKED-FRESHNESS] {name}: no freshness rule")
    return lines


