def _identity_tolerance(headline: pd.Series) -> pd.Series:
    """Per-period tolerance: max(0.1 units, 0.01% of the headline value)."""
    return np.maximum(0.1, 1e-4 * headline.abs())


class _IdentityPeriods(NamedTuple):
    rule: str
    checked: int                 # complete periods where no member is defining (independent)
    skipped: int                 # periods with some but not all members present
    definitional: Dict[str, int]  # defining series -> complete periods it defines
    gaps: List[Tuple[str, List[str]]] = []  # (period, missing members) of each skipped period


def _defining_member(group: Tuple[str, ...], date: str, catalog: Dict[str, dict]) -> Optional[str]:
    """
    The member of `group` computed from the other members at `date`, or None:
    its catalog origin segment there is `derived` and all its inputs are other members.
    """
    for sid in group:
        entry = catalog.get(sid)
        if entry is None:
            continue
        try:
            seg = flags.segment_for(entry, date)
        except ValueError:
            continue
        inputs = set(seg.get("inputs") or [])
        if seg.get("class") == "derived" and inputs and inputs <= set(group) - {sid}:
            return sid
    return None


def _identity_periods(df: pd.DataFrame, catalog: Optional[Dict[str, dict]] = None):
    """Per-rule period counts, and the derived series covered by an independent period."""
    if catalog is None:
        catalog = flags.load_catalog()
    results: List[_IdentityPeriods] = []
    covered: set = set()
    if not {"date", "series_id", "value"}.issubset(df.columns):
        return results, covered
    present = set(df["series_id"].values)
    for rule, groups in IDENTITY_RULES:
        checked = skipped = 0
        definitional: Dict[str, int] = {}
        gaps: List[Tuple[str, List[str]]] = []
        found = False
        for group in groups:
            if not present.intersection(group):
                continue
            found = True
            sub = df[df["series_id"].isin(group)]
            piv = sub.pivot_table(index="date", columns="series_id", values="value").reindex(columns=list(group))
            complete = piv.notna().all(axis=1)
            skipped += int((~complete).sum())
            for date, row in piv[~complete].iterrows():
                gaps.append((str(date), [sid for sid in group if pd.isna(row[sid])]))
            for date in sorted(piv.index[complete]):
                defining = _defining_member(group, str(date), catalog)
                if defining is None:
                    checked += 1
                    covered.update(group)
                else:
                    definitional[defining] = definitional.get(defining, 0) + 1
        if found:
            results.append(_IdentityPeriods(rule, checked, skipped, definitional, sorted(gaps)))
    return results, covered


def identity_coverage(df: pd.DataFrame, catalog: Optional[Dict[str, dict]] = None) -> List[Tuple[str, int, int]]:
    """
    Report (rule, checked, skipped) for each identity whose series appear in df.

    A period is 'checked' when every component is present and non-NaN and no component is
    computed from the others (such periods hold by definition and are reported by
    definitional_coverage instead). It is 'skipped' when at least one component is present
    but not all of them.
    """
    return [(r.rule, r.checked, r.skipped) for r in _identity_periods(df, catalog)[0]]


def definitional_coverage(df: pd.DataFrame, catalog: Optional[Dict[str, dict]] = None) -> List[Tuple[str, str, int]]:
    """(rule, defining series, complete periods) for identities that hold by definition."""
    return [(r.rule, sid, n) for r in _identity_periods(df, catalog)[0] for sid, n in sorted(r.definitional.items())]


def uncovered_derived(df: pd.DataFrame, catalog: Optional[Dict[str, dict]] = None) -> List[str]:
    """
    Published derived series in df (open catalog origin segment is `derived`) that are a
    non-defining member of no independent identity period, sorted.
    """
    if catalog is None:
        catalog = flags.load_catalog()
    if "series_id" not in df.columns:
        return []
    _, covered = _identity_periods(df, catalog)
    derived = set()
    for sid in set(df["series_id"].dropna().unique()):
        segs = (catalog.get(sid) or {}).get("origin") or []
        if any(flags.period(s["to"]) == flags.OPEN and s.get("class") == "derived" for s in segs):
            derived.add(sid)
    return sorted(derived - covered)


def _values_of(rows: pd.DataFrame) -> dict:
    """{period: value} of the rows a warning is about."""
    return {str(d): float(v) for d, v in zip(rows["date"], rows["value"])} if "date" in rows.columns else {}


def validate_tier2_details(df: pd.DataFrame, dataset_name: str = "dataset") -> Tuple[List[str], List[Warning]]:
    """
    Executes Tier-2 economic sanity and domain checks.
    Returns:
        (errors, warnings)
        - errors: Hard mathematical accounting failures (strings).
        - warnings: Structured Warning instances for review.
    """
    errors: List[str] = []
    warnings: List[Warning] = []

    # 1. Plausibility envelope review checks, sign checks, unit checks, unruled series
    if "series_id" in df.columns:
        rules = load_rules()
        series_rules = rules.get("series", {})
        unique_sids = sorted(df["series_id"].dropna().unique())

        for series_id in unique_sids:
            if series_id not in series_rules:
                # Unruled-series check
                msg = (
                    f"[{dataset_name}] Unchecked series: {series_id} has no plausibility rule "
                    f"in pipeline/metadata/plausibility_rules.yaml"
                )
                warnings.append(
                    Warning(
                        dataset=dataset_name,
                        series=series_id,
                        check="unchecked_series",
                        periods=[],
                        message=msg,
                    )
                )
                continue

            rule = series_rules[series_id]

            # Unit check (fatal Tier 2 error)
            if "unit" in rule and "unit" in df.columns:
                expected_unit = rule["unit"]
                sub_unit = df[df["series_id"] == series_id]
                bad_units = sub_unit[sub_unit["unit"] != expected_unit]
                if not bad_units.empty:
                    other_units = sorted(bad_units["unit"].unique().tolist())
                    other_str = other_units[0] if len(other_units) == 1 else str(other_units)
                    periods = bad_units["date"].tolist() if "date" in bad_units.columns else []
                    errors.append(
                        f"[{dataset_name}] Unit Mismatch: {series_id} declared {expected_unit}, "
                        f"found {other_str} in periods: {periods}"
                    )

            if rule.get("exempt"):
                continue

            if "value" not in df.columns:
                continue

            sub = df[df["series_id"] == series_id].dropna(subset=["value"])

            # Envelope check
            min_v = rule.get("min")
            max_v = rule.get("max")
            if min_v is not None and max_v is not None:
                out_of_bounds = sub[(sub["value"] < min_v) | (sub["value"] > max_v)]
                if not out_of_bounds.empty:
                    examples = out_of_bounds[["date", "series_id", "value"]].head(3).to_dict(orient="records")
                    periods = out_of_bounds["date"].tolist() if "date" in out_of_bounds.columns else []
                    msg = (
                        f"[{dataset_name}] Plausibility Notice: Series matching '{series_id}' outside [{min_v}, {max_v}]. "
                        f"Found {len(out_of_bounds)} observations requiring review. Examples: {examples}"
                    )
                    warnings.append(
                        Warning(
                            dataset=dataset_name,
                            series=series_id,
                            check="envelope",
                            periods=periods,
                            message=msg,
                            values=_values_of(out_of_bounds),
                        )
                    )

            # Sign check
            sign = rule.get("sign")
            if sign == "positive":
                bad_sign = sub[sub["value"] <= 0]
            elif sign == "non_negative":
                bad_sign = sub[sub["value"] < 0]
            else:
                bad_sign = pd.DataFrame()

            if not bad_sign.empty:
                examples = bad_sign[["date", "series_id", "value"]].head(3).to_dict(orient="records")
                periods = bad_sign["date"].tolist() if "date" in bad_sign.columns else []
                msg = (
                    f"[{dataset_name}] Sign Notice: {series_id} must be {sign}; "
                    f"{len(bad_sign)} observation(s) violate it. Examples: {examples}"
                )
                warnings.append(
                    Warning(
                        dataset=dataset_name,
                        series=series_id,
                        check="sign",
                        periods=periods,
                        message=msg,
                        values=_values_of(bad_sign),
                    )
                )

            # Jumps and scale shifts across consecutive available observations
            if len(sub) > 1 and "date" in sub.columns:
                sub_sorted = sub.sort_values("date").reset_index(drop=True)
                median_abs = float(np.median(np.abs(sub_sorted["value"])))
                defaults = rules.get("defaults", {})
                scale_window = defaults.get("scale_shift", [500, 2000])
                scale_min_r, scale_max_r = float(scale_window[0]), float(scale_window[1])
                min_share = float(defaults.get("scale_shift_min_share", 0.1))

                jump_rule = rule.get("jump", {})
                jump_measure = jump_rule.get("measure", "log")
                threshold = float(jump_rule.get("threshold", np.log(3.0)))
                # A scaled change uses the scale the rule was derived with, not the data checked
                scale = float(jump_rule.get("scale") or median_abs or 1.0)

                # Plain arrays: row-by-row .iloc access dominated the gatekeeper's run time
                values_arr = sub_sorted["value"].to_numpy(dtype=float)
                dates_arr = sub_sorted["date"].astype(str).to_numpy()
                flags_arr = (sub_sorted["status_flag"].astype(str).to_numpy()
                             if "status_flag" in sub_sorted.columns else None)

                for i in range(len(sub_sorted) - 1):
                    val_prev = float(values_arr[i])
                    val_curr = float(values_arr[i + 1])
                    date_prev = str(dates_arr[i])
                    date_curr = str(dates_arr[i + 1])
                    abs_prev = abs(val_prev)
                    abs_curr = abs(val_curr)

                    # Scale shift check
                    if abs_prev > 0 and abs_curr > 0:
                        ratio_scale = abs_curr / abs_prev
                        in_scale_window = (
                            (scale_min_r <= ratio_scale <= scale_max_r)
                            or ((1.0 / scale_max_r) <= ratio_scale <= (1.0 / scale_min_r))
                        )
                        if in_scale_window:
                            eligible = True
                            if sign == "any":
                                eligible = (
                                    abs_prev >= min_share * median_abs
                                    and abs_curr >= min_share * median_abs
                                )
                            if eligible:
                                r_str = f"{ratio_scale:.4g}"
                                msg = (
                                    f"[{dataset_name}] Scale Shift: {series_id} changed ×{r_str} "
                                    f"between {date_prev} and {date_curr} (suspected thousands/millions error)"
                                )
                                warnings.append(
                                    Warning(
                                        dataset=dataset_name,
                                        series=series_id,
                                        check="scale_shift",
                                        periods=[date_curr],
                                        message=msg,
                                        values={date_prev: val_prev, date_curr: val_curr},
                                    )
                                )

                    # Jump check. No pair is skipped for its sign; a log
                    # move to or from a value <= 0 is infinite, and scaled changes work across zero
                    if jump_measure == "log":
                        if val_prev > 0 and val_curr > 0:
                            move = abs(np.log(val_curr / val_prev))
                        else:
                            move = np.inf
                    elif jump_measure == "scaled":
                        move = abs(val_curr - val_prev) / scale
                    else:
                        raise ValueError(f"{series_id}: unknown jump measure {jump_measure!r} (log or scaled)")

                    if move > threshold:
                        span = period_span(date_prev, date_curr)
                        flag_curr = flags_arr[i + 1] if flags_arr is not None else ""
                        flag_prev = flags_arr[i] if flags_arr is not None else ""
                        if jump_measure == "log":
                            r_str = "×" + (f"{np.exp(move):.4g}" if np.isfinite(move) else "inf (to or from a value <= 0)")
                            thresh_str = f"×{np.exp(threshold):.4g}"
                        else:
                            r_str = f"{move:.4g} × scale {scale:.4g}"
                            thresh_str = f"{threshold:.4g}"
                        if flag_curr == "B" or flag_prev == "B":
                            b_date = date_curr if flag_curr == "B" else date_prev
                            msg = f"{series_id} {b_date}: move {r_str} at a B-flagged observation"
                            warnings.append(
                                Warning(
                                    dataset=dataset_name,
                                    series=series_id,
                                    check="break",
                                    periods=[b_date],
                                    message=msg,
                                )
                            )
                        else:
                            msg = (
                                f"[{dataset_name}] Jump Notice: {series_id} moved {r_str} "
                                f"(threshold {thresh_str}) from {date_prev} to {date_curr}, spanning {span} period(s)"
                            )
                            warnings.append(
                                Warning(
                                    dataset=dataset_name,
                                    series=series_id,
                                    check="jump",
                                    periods=[date_curr],
                                    message=msg,
                                    values={date_prev: val_prev, date_curr: val_curr},
                                )
                            )

    # 2. Accounting Check: Government Public Budget (CBI Sheet 6-1 / seeds)
    for tot_rev, cur_rev, inv_rev, tot_exp, cur_exp, inv_exp in BUDGET_SID_GROUPS:
        if any(df["series_id"].isin([tot_rev, cur_rev, inv_rev, tot_exp, cur_exp, inv_exp])):
            piv = df.pivot_table(index="date", columns="series_id", values="value")
            
            # Revenues check: Current + Investment == Total Revenues
            if tot_rev in piv and cur_rev in piv and inv_rev in piv:
                rev_sub = piv[[tot_rev, cur_rev, inv_rev]].dropna()
                if not rev_sub.empty:
                    diff = np.abs((rev_sub[cur_rev] + rev_sub[inv_rev]) - rev_sub[tot_rev])
                    bad_rev = diff[diff > 0.05]
                    if not bad_rev.empty:
                        errors.append(
                            f"[{dataset_name}] Budget Accounting Discrepancy: Current + Investment != Total Revenues for periods: {bad_rev.index.tolist()}"
                        )

            # Expenditures check: Current + Investment == Total Expenditures
            if tot_exp in piv and cur_exp in piv and inv_exp in piv:
                exp_sub = piv[[tot_exp, cur_exp, inv_exp]].dropna()
                if not exp_sub.empty:
                    diff = np.abs((exp_sub[cur_exp] + exp_sub[inv_exp]) - exp_sub[tot_exp])
                    bad_exp = diff[diff > 0.05]
                    if not bad_exp.empty:
                        errors.append(
                            f"[{dataset_name}] Budget Accounting Discrepancy: Current + Investment != Total Expenditures for periods: {bad_exp.index.tolist()}"
                        )

    # 2b. Accounting Check: Fiscal Balance == Total Revenue - Total Expenditure
    for bal_id, rev_id, exp_id in FISCAL_BALANCE_SIDS:
        if all(s in df["series_id"].values for s in (bal_id, rev_id, exp_id)):
            piv = df.pivot_table(index="date", columns="series_id", values="value")
            sub_bal = piv[[bal_id, rev_id, exp_id]].dropna()
            if not sub_bal.empty:
                diff = np.abs((sub_bal[rev_id] - sub_bal[exp_id]) - sub_bal[bal_id])
                bad_bal = diff[diff > _identity_tolerance(sub_bal[bal_id])]
                if not bad_bal.empty:
                    errors.append(
                        f"[{dataset_name}] Fiscal Balance Identity Discrepancy: Revenue - Expenditure != Balance for periods: {bad_bal.index.tolist()}"
                    )

    # 3. Accounting Check: GDP (Real Oil + Real Non-Oil == Headline Real GDP)
    gdp_pairs = [
        {"headline": "gdp.real", "oil": "gdp.real_oil", "nonoil": "gdp.real_nonoil"},
        {"headline": "cosit.gdp_real", "oil": "cosit.gdp_real_oil", "nonoil": "cosit.gdp_real_nonoil"},
    ]
    for gdp_sids in gdp_pairs:
        if all(s in df["series_id"].values for s in gdp_sids.values()):
            piv = df.pivot_table(index="date", columns="series_id", values="value")
            sub_gdp = piv[[gdp_sids["headline"], gdp_sids["oil"], gdp_sids["nonoil"]]].dropna()
            if not sub_gdp.empty:
                diff = np.abs((sub_gdp[gdp_sids["oil"]] + sub_gdp[gdp_sids["nonoil"]]) - sub_gdp[gdp_sids["headline"]])
                bad_gdp = diff[diff > 0.1]
                if not bad_gdp.empty:
                    errors.append(
                        f"[{dataset_name}] GDP Accounting Discrepancy: Real Oil + Real Non-Oil != Real Headline for quarters: {bad_gdp.index.tolist()}"
                    )

    # 3b. Accounting Check: GDP (Nominal Oil + Nominal Non-Oil == Headline Nominal GDP)
    for nom_id, oil_id, nonoil_id in NOMINAL_GDP_SIDS:
        if all(s in df["series_id"].values for s in (nom_id, oil_id, nonoil_id)):
            piv = df.pivot_table(index="date", columns="series_id", values="value")
            sub_nom = piv[[nom_id, oil_id, nonoil_id]].dropna()
            if not sub_nom.empty:
                diff = np.abs((sub_nom[oil_id] + sub_nom[nonoil_id]) - sub_nom[nom_id])
                bad_nom = diff[diff > _identity_tolerance(sub_nom[nom_id])]
                if not bad_nom.empty:
                    errors.append(
                        f"[{dataset_name}] GDP Accounting Discrepancy: Nominal Oil + Nominal Non-Oil != Nominal Headline for quarters: {bad_nom.index.tolist()}"
                    )

    # 4. Money Supply Check: M1 < M2
    money_pairs = [("money.m1", "money.m2"), ("cbi.money.m1", "cbi.money.m2")]
    for m1_id, m2_id in money_pairs:
        if m1_id in df["series_id"].values and m2_id in df["series_id"].values:
            piv = df.pivot_table(index="date", columns="series_id", values="value")
            sub_m = piv[[m1_id, m2_id]].dropna()
            if not sub_m.empty:
                inversion = sub_m[sub_m[m1_id] >= sub_m[m2_id]]
                if not inversion.empty:
                    errors.append(
                        f"[{dataset_name}] Money Supply Inversion: M1 >= M2 detected in periods: {inversion.index.tolist()}"
                    )

    # 5. BIS LBS Cross-Border Banking Checks
    bis_sids = {"bis.lbs.claims_total", "bis.lbs.liabilities_total", "bis.lbs.net_position"}
    if bis_sids.issubset(set(df["series_id"].values)):
        piv = df.pivot_table(index="date", columns="series_id", values="value")
        sub_bis = piv[list(bis_sids)].dropna()
        if not sub_bis.empty:
            diff_net = np.abs((sub_bis["bis.lbs.liabilities_total"] - sub_bis["bis.lbs.claims_total"]) - sub_bis["bis.lbs.net_position"])
            bad_net = diff_net[diff_net > 0.05]
            if not bad_net.empty:
                errors.append(
                    f"[{dataset_name}] BIS Net Position Discrepancy: Liabilities - Claims != Net Position for quarters: {bad_net.index.tolist()}"
                )

        if "bis.lbs.liabilities_banks" in df["series_id"].values and "bis.lbs.liabilities_nonbank" in df["series_id"].values:
            sub_sec = piv[["bis.lbs.liabilities_total", "bis.lbs.liabilities_banks", "bis.lbs.liabilities_nonbank"]].dropna()
            if not sub_sec.empty:
                # Total must accommodate banks + nonbank with minor unallocated residual tolerance
                discrep = (sub_sec["bis.lbs.liabilities_banks"] + sub_sec["bis.lbs.liabilities_nonbank"]) - sub_sec["bis.lbs.liabilities_total"]
                bad_discrep = discrep[discrep > 1.0]
                if not bad_discrep.empty:
                    errors.append(
                        f"[{dataset_name}] BIS Sector Liability Discrepancy: Banks + Non-Bank > Total Liabilities for quarters: {bad_discrep.index.tolist()}"
                    )

    # 6. OECD DAC: no identity (net ODA minus grants mixes two concepts, so it is not published)


    # 7. Balance of Payments (BOP) Identities (tolerance max(0.25, 1e-4 * headline.abs()))
    # 7a. Trade balance = exports - imports
    tb_sids = {"bop.trade_balance", "trade.exports_total", "trade.imports_total"}
    if tb_sids.issubset(set(df["series_id"].values)):
        piv = df.pivot_table(index="date", columns="series_id", values="value")
        sub_tb = piv[list(tb_sids)].dropna()
        if not sub_tb.empty:
            diff_tb = np.abs((sub_tb["trade.exports_total"] - sub_tb["trade.imports_total"]) - sub_tb["bop.trade_balance"])
            tol_tb = np.maximum(0.25, 1e-4 * sub_tb["bop.trade_balance"].abs())
            bad_tb = diff_tb[diff_tb > tol_tb]
            if not bad_tb.empty:
                errors.append(
                    f"[{dataset_name}] BOP Trade Balance Identity Discrepancy: Exports - Imports != Trade Balance for quarters: {bad_tb.index.tolist()}"
                )

    # 7b. Exports = crude oil + oil products + non-oil
    exp_sids = {"trade.exports_total", "trade.exports_crude_oil", "trade.exports_oil_products", "trade.exports_nonoil"}
    if exp_sids.issubset(set(df["series_id"].values)):
        piv = df.pivot_table(index="date", columns="series_id", values="value")
        sub_exp = piv[list(exp_sids)].dropna()
        if not sub_exp.empty:
            diff_exp = np.abs((sub_exp["trade.exports_crude_oil"] + sub_exp["trade.exports_oil_products"] + sub_exp["trade.exports_nonoil"]) - sub_exp["trade.exports_total"])
            tol_exp = np.maximum(0.25, 1e-4 * sub_exp["trade.exports_total"].abs())
            bad_exp = diff_exp[diff_exp > tol_exp]
            if not bad_exp.empty:
                errors.append(
                    f"[{dataset_name}] BOP Exports Decomposition Discrepancy: Crude + Products + Non-oil != Total Exports for quarters: {bad_exp.index.tolist()}"
                )

    # 7c. Imports = government + private
    imp_sids = {"trade.imports_total", "trade.imports_government", "trade.imports_private"}
    if imp_sids.issubset(set(df["series_id"].values)):
        piv = df.pivot_table(index="date", columns="series_id", values="value")
        sub_imp = piv[list(imp_sids)].dropna()
        if not sub_imp.empty:
            diff_imp = np.abs((sub_imp["trade.imports_government"] + sub_imp["trade.imports_private"]) - sub_imp["trade.imports_total"])
            tol_imp = np.maximum(0.25, 1e-4 * sub_imp["trade.imports_total"].abs())
            bad_imp = diff_imp[diff_imp > tol_imp]
            if not bad_imp.empty:
                errors.append(
                    f"[{dataset_name}] BOP Imports Decomposition Discrepancy: Government + Private != Total Imports for quarters: {bad_imp.index.tolist()}"
                )

    # 7d. Current account = trade balance + services + income + transfers
    ca_sids = {"bop.current_account", "bop.trade_balance", "bop.services_net", "bop.income_net", "bop.transfers_net"}
    if ca_sids.issubset(set(df["series_id"].values)):
        piv = df.pivot_table(index="date", columns="series_id", values="value")
        sub_ca = piv[list(ca_sids)].dropna()
        if not sub_ca.empty:
            diff_ca = np.abs((sub_ca["bop.trade_balance"] + sub_ca["bop.services_net"] + sub_ca["bop.income_net"] + sub_ca["bop.transfers_net"]) - sub_ca["bop.current_account"])
            tol_ca = np.maximum(0.25, 1e-4 * sub_ca["bop.current_account"].abs())
            bad_ca = diff_ca[diff_ca > tol_ca]
            if not bad_ca.empty:
                errors.append(
                    f"[{dataset_name}] BOP Current Account Identity Discrepancy: Trade + Services + Income + Transfers != Current Account for quarters: {bad_ca.index.tolist()}"
                )

    # 8. Monetary Orderings: Currency Outside Banks <= M0, Currency Outside Banks <= M1
    cur_m0_pairs = [
        ("money.currency_outside_banks", "money.m0"),
        ("cbi.money.currency_outside_banks", "cbi.money.m0"),
    ]
    for cur_id, m0_id in cur_m0_pairs:
        if cur_id in df["series_id"].values and m0_id in df["series_id"].values:
            piv = df.pivot_table(index="date", columns="series_id", values="value")
            sub_cur0 = piv[[cur_id, m0_id]].dropna()
            if not sub_cur0.empty:
                bad_cur0 = sub_cur0[sub_cur0[cur_id] > sub_cur0[m0_id]]
                if not bad_cur0.empty:
                    examples = bad_cur0.to_dict(orient="index")
                    errors.append(
                        f"[{dataset_name}] Monetary Ordering Inversion: Currency Outside Banks > M0 for periods: {examples}"
                    )

    cur_m1_pairs = [
        ("money.currency_outside_banks", "money.m1"),
        ("cbi.money.currency_outside_banks", "cbi.money.m1"),
    ]
    for cur_id, m1_id in cur_m1_pairs:
        if cur_id in df["series_id"].values and m1_id in df["series_id"].values:
            piv = df.pivot_table(index="date", columns="series_id", values="value")
            sub_cur1 = piv[[cur_id, m1_id]].dropna()
            if not sub_cur1.empty:
                bad_cur1 = sub_cur1[sub_cur1[cur_id] > sub_cur1[m1_id]]
                if not bad_cur1.empty:
                    examples = bad_cur1.to_dict(orient="index")
                    errors.append(
                        f"[{dataset_name}] Monetary Ordering Inversion: Currency Outside Banks > M1 for periods: {examples}"
                    )

    # 8b. Identity gaps: a period where some but not all members of an
    # identity are published cannot be checked; it is a review notice unless listed as expected
    if {"date", "series_id", "value"}.issubset(df.columns):
        expected = {(str(e["rule"]), str(e["period"]), frozenset(e["missing"])) for e in load_expected_gaps()}
        last = df.dropna(subset=["value"]).groupby("series_id")["date"].max().astype(str).to_dict()
        for r in _identity_periods(df)[0]:
            for period, missing in r.gaps:
                if (r.rule, period, frozenset(missing)) in expected:
                    continue
                # `period: latest`: the missing series have not been published that far yet (a
                # ragged edge between sources); freshness reports them if they become overdue
                if (r.rule, "latest", frozenset(missing)) in expected and all(
                        sid in last and period > last[sid] for sid in missing):
                    continue
                for sid in missing:
                    warnings.append(Warning(
                        dataset=dataset_name, series=sid, check="gap", periods=[period],
                        message=f"[{dataset_name}] [GAP] {r.rule} {period}: {', '.join(missing)} missing, "
                                "so the identity is not checked",
                    ))

    # 8c. Continuity: a monthly, quarterly or annual series with a period missing inside its range cannot be
    # told from a source that dropped it, so it is a review notice unless the series is listed as lacking it
    if {"date", "series_id"}.issubset(df.columns):
        listed = load_expected_missing()
        for sid, missing in interior_gaps(df).items():
            rule = listed.get(sid)
            if rule is not None and (rule["periods"] is None or set(missing) <= rule["periods"]):
                continue
            span = sorted(str(d) for d in df.loc[df["series_id"] == sid, "date"])
            warnings.append(Warning(
                dataset=dataset_name, series=sid, check="gap", periods=missing,
                message=f"[{dataset_name}] [GAP] {sid}: no value for {_runs(missing)} between {span[0]} and {span[-1]}",
            ))

    # 8d. New-point volatility: each of a series' latest periods against the moves just before it
    if load_new_point_check()["enabled"]:
        warnings += new_point_warnings(df, dataset_name, load_new_point_check())

    # 9. Unfinished Period Check
    if {"date", "realtime_start", "status_flag", "series_id"}.issubset(df.columns):
        # U (low reliability, e.g. transcribed values) makes no claim of finality either
        non_pe_mask = ~df["status_flag"].isin(["P", "E", "U"])
        if non_pe_mask.any():
            sub_pe = df[non_pe_mask][["series_id", "date", "status_flag", "realtime_start"]].astype(str)

            # Parse each distinct date and vintage once; unparseable values are left to Tier 1
            def _parse_all(values, parse):
                parsed = {}
                for v in values:
                    try:
                        parsed[v] = parse(v)
                    except Exception:
                        parsed[v] = None
                return parsed

            ends = _parse_all(sub_pe["date"].unique(), period_end)
            vintages = _parse_all(sub_pe["realtime_start"].unique(), lambda v: pd.Timestamp(v).floor("D"))
            for series_id, dt_str, flag, vt_str in sub_pe.itertuples(index=False):
                end, vt = ends[dt_str], vintages[vt_str]
                if end is None or vt is None or not end > vt:
                    continue
                end_str = end.strftime("%Y-%m-%d")
                msg = (
                    f"[{dataset_name}] Unfinished Period Notice: {series_id} {dt_str} ends {end_str} "
                    f"after vintage {vt_str}; requires status flag P, E or U, found {flag}"
                )
                warnings.append(
                    Warning(
                        dataset=dataset_name,
                        series=series_id,
                        check="unfinished_period",
                        periods=[dt_str],
                        message=msg,
                    )
                )

    return errors, warnings


SANITY_DATASET = "cross-source"


def _published(frames: Dict[str, pd.DataFrame], series_id: str) -> pd.Series:
    """A series' values by date (sorted), from whichever of the frames holds it."""
    parts = [df.loc[df["series_id"] == series_id, ["date", "value"]] for df in frames.values()
             if {"series_id", "date", "value"}.issubset(df.columns)]
    if not parts:
        return pd.Series(dtype=float)
    rows = pd.concat(parts).dropna(subset=["value"]).drop_duplicates("date")
    return rows.set_index(rows["date"].astype(str))["value"].astype(float).sort_index()


def _quarter_end(quarter: str) -> Tuple[str, str]:
    """('YYYY-MM', 'YYYY-MM-DD') of a quarter's last month and last day."""
    end = pd.Period(quarter, freq="Q").end_time
    return end.strftime("%Y-%m"), end.strftime("%Y-%m-%d")


def _previous_quarter(quarter: str) -> str:
    return str(pd.Period(quarter, freq="Q") - 1).replace("Q", "-Q")


def _value_on(series: pd.Series, day: str) -> Optional[float]:
    """The last value on or before `day` (dates YYYY-MM-DD)."""
    before = series[series.index <= day]
    return float(before.iloc[-1]) if len(before) else None


def sanity_warnings(frames: Dict[str, pd.DataFrame], checks: Optional[List[dict]] = None) -> List[Warning]:
    """
    Cross-source sanity checks (pipeline/metadata/sanity_checks.yaml). Not
    accounting identities: a breach is a Tier-2 review notice ([SANITY]), never fatal, and is not
    counted in the identity coverage. A check whose series are not among `frames` is skipped.
    Each warning records both sides' values, so a revision of either is reviewed again.
    """
    checks = load_sanity_checks() if checks is None else checks
    out: List[Warning] = []
    for c in checks:
        a, b = _published(frames, c["a"]), _published(frames, c["b"])
        if a.empty or b.empty:
            continue
        if c["align"] == "same_period":
            lo, hi = (float(x) for x in c["band"])
            for d in sorted(a.index.intersection(b.index)):
                if b[d] == 0:
                    continue
                ratio = a[d] / b[d]
                if lo <= ratio <= hi:
                    continue
                out.append(Warning(
                    dataset=SANITY_DATASET, series=c["id"], check="sanity", periods=[d],
                    message=(f"[SANITY] {c['id']} {d}: ratio {ratio:.4g} outside {lo:g}-{hi:g} "
                             f"({c['a']} {a[d]:.6g}, {c['b']} {b[d]:.6g})"),
                    values={d: float(a[d]), f"{d} {c['b']}": float(b[d])},
                ))
            continue
        # quarter_end_change: a quarterly flow against the change of a monthly stock over the quarter
        conv = c.get("convert") or {}
        divide = _published(frames, conv["divide_by"]) if conv.get("divide_by") else None
        scale = float(conv.get("scale", 1.0))
        tol_abs, tol_rel = float(c["tolerance"]["absolute"]), float(c["tolerance"]["relative"])
        for q in sorted(a.index):
            (m1, d1), (m0, d0) = _quarter_end(q), _quarter_end(_previous_quarter(q))
            if m1 not in b.index or m0 not in b.index:
                continue
            if divide is not None:
                f1, f0 = _value_on(divide, d1), _value_on(divide, d0)
                if not f1 or not f0:
                    continue
                change = (b[m1] / f1 - b[m0] / f0) * scale  # each stock at its own quarter-end rate
            else:
                change = (b[m1] - b[m0]) * scale
            tol = max(tol_abs, tol_rel * abs(change))
            if abs(a[q] - change) <= tol:
                continue
            out.append(Warning(
                dataset=SANITY_DATASET, series=c["id"], check="sanity", periods=[q],
                message=(f"[SANITY] {c['id']} {q}: {c['a']} {a[q]:.6g} vs {c['b']} change {change:.6g} "
                         f"(gap {abs(a[q] - change):.6g}, tolerance {tol:.6g})"),
                values={q: float(a[q]), f"{q} {c['b']} change": float(change)},
            ))
    return out


def validate_tier2_domain(df: pd.DataFrame, dataset_name: str = "dataset") -> Tuple[List[str], List[str]]:
    """
    Executes Tier-2 economic sanity and domain checks.
    Returns:
        (errors, warnings)
        - errors: Hard mathematical accounting failures.
        - warnings: Plausibility envelope breaches for human review (strings).
    """
    errors, warnings = validate_tier2_details(df, dataset_name=dataset_name)
    return errors, [w.message for w in warnings if w.check != "break"]


def validate_file(file_path: Path) -> Tuple[bool, List[str], List[str]]:
    """
    Loads and validates a single parquet or csv file.
    Returns:
        (passed, errors, warnings)
    """
    dataset_name = file_path.name
    try:
        if file_path.suffix == ".parquet":
            df = pd.read_parquet(file_path)
        elif file_path.suffix == ".csv":
            df = pd.read_csv(file_path)
        else:
            return False, [f"[{dataset_name}] Unsupported file format: {file_path.suffix}"], []
    except Exception as e:
        return False, [f"[{dataset_name}] Failed to read file: {e}"], []

    # Tier 1: Schema Checks (Fatal if failed)
    t1_errors = validate_dataframe(df, dataset_name=dataset_name)
    if t1_errors:
        return False, t1_errors, []

    # Tier 2: Domain and Economic Checks
    t2_errors, t2_warnings = validate_tier2_domain(df, dataset_name=dataset_name)
    if t2_errors:
        return False, t2_errors, t2_warnings

    return True, [], t2_warnings


def run_gatekeeper(target_files: List[Path], acks: List[dict], *, release: bool, freshness: bool,
                   as_of: pd.Timestamp, all_datasets: bool) -> int:
    """
    Run every check on `target_files` and print the report; return the exit code (0 pass, 1 fail).
    `all_datasets` enables stale-acknowledgement detection (a run over all garden and seed tables).
    Used by main() and by export_release.
    """
    if not target_files:
        print("No target datasets found in pipeline/data/garden/ or pipeline/seeds/.")
        print("Validator engine is ready and active. (Run: python pipeline/validate.py path/to/file.parquet)")
        if release:
            # A release gate with nothing to check must not pass
            print("Release mode: no tables were checked, so the release gate fails.")
            return 1
        return 0

    all_passed = True
    total_obs = 0
    total_warnings = 0
    matched_ack_indices = set()
    expired_acks: set = set()   # indices of acknowledgements past review_by that matched
    due_acks: set = set()
    production = production_tables()
    fresh_tables: Dict[str, pd.DataFrame] = {}

    for f in target_files:
        print(f"\nScanning: {f.name} ...")
        dataset_name = f.name
        try:
            if f.suffix == ".parquet":
                df = pd.read_parquet(f)
            elif f.suffix == ".csv":
                df = pd.read_csv(f)
            else:
                passed, errors, detail_warnings = False, [f"[{dataset_name}] Unsupported file format: {f.suffix}"], []
                df = None
        except Exception as e:
            passed, errors, detail_warnings = False, [f"[{dataset_name}] Failed to read file: {e}"], []
            df = None

        if df is not None and f.stem in production and {"series_id", "date"}.issubset(df.columns):
            fresh_tables[f.stem] = df

        if df is not None:
            t1_errors = validate_dataframe(df, dataset_name=dataset_name)
            if t1_errors:
                passed = False
                errors = t1_errors
                detail_warnings = []
            else:
                t2_errors, detail_warnings = validate_tier2_details(df, dataset_name=dataset_name)
                if t2_errors:
                    passed = False
                    errors = t2_errors
                else:
                    passed = True
                    errors = []

        break_warnings = [w for w in detail_warnings if w.check == "break"]
        candidate_warnings = [w for w in detail_warnings if w.check != "break"]

        # Match acknowledgements (per period, value-tied, with a review-by date)
        ack_list = []
        unack_list = []
        changed_lines = []
        for w in candidate_warnings:
            m = match_warning(w, acks, dataset_name, as_of)
            if m is None:
                unack_list.append(w)
                continue
            matched_ack_indices.add(m.index)
            if m.state in ("applies", "due"):
                ack_list.append((w, acks[m.index]))
                if m.state == "due":
                    due_acks.add(m.index)
                continue
            unack_list.append(w)
            if m.state == "expired":
                expired_acks.add(m.index)
            else:
                changed_lines.append(f"[CHANGED] {w.check} {w.series} {', '.join(map(str, w.periods))}: {m.detail}")

        total_warnings += len(unack_list)

        if passed and df is not None:
            total_obs += len(df)
            status_text = "[PASS]"
            if unack_list:
                status_text += f" (with {len(unack_list)} notice(s))"
            print(f"  {status_text} {len(df):,} observations across {df['series_id'].nunique()} series.")
            for w in unack_list:
                print(f"    [NOTICE] {w.message}")
            for line in changed_lines:
                print(f"    {line}")
            for w, ack in ack_list:
                print(f"    [ACKNOWLEDGED] {w.message} — {ack['reason']}")
            for bw in break_warnings:
                print(f"    [BREAK] {bw.message}")
        else:
            all_passed = False
            print("  [FAIL] Critical Issues Detected:")
            for err in errors:
                print(f"    - {err}")
            for w in unack_list:
                print(f"    [NOTICE] {w.message}")
            for line in changed_lines:
                print(f"    {line}")
            for w, ack in ack_list:
                print(f"    [ACKNOWLEDGED] {w.message} — {ack['reason']}")
            for bw in break_warnings:
                print(f"    [BREAK] {bw.message}")

        # Identity coverage is informational only and never counted as a review notice
        if df is not None:
            periods, _ = _identity_periods(df)
            for r in periods:
                print(f"    [INFO] {r.rule}: checked {r.checked} period(s), skipped {r.skipped} (missing components)")
                # Only the 2024-2025 bulletin years are an independent fiscal check
                note = "; 2004-2023 from a seed of unknown origin" if r.rule == "Fiscal balance" else ""
                if r.checked or not r.definitional:
                    print(f"    [IDENTITY] {r.rule} (independent): checked {r.checked}, skipped {r.skipped}{note}")
                for sid, n in sorted(r.definitional.items()):
                    print(f"    [IDENTITY] {r.rule} (definitional: {sid}): {n} period(s), not a check")
            for sid in uncovered_derived(df):
                print(f"    [DERIVED] {sid}: no independent identity check")
            if "series_id" in df.columns:
                rules = load_rules()
                s_rules = rules.get("series", {})
                u_series = sorted(df["series_id"].dropna().unique())
                n_exempt = sum(1 for s in u_series if s in s_rules and s_rules[s].get("exempt"))
                n_unchecked = sum(1 for s in u_series if s not in s_rules)
                n_checked = len(u_series) - n_exempt - n_unchecked
                print(f"    [COVERAGE] series: {n_checked} checked, {n_exempt} exempt, {n_unchecked} unchecked")
            if "status_flag" in df.columns:
                flag_counts = df["status_flag"].value_counts().to_dict()
                p_c = flag_counts.get("P", 0)
                e_c = flag_counts.get("E", 0)
                b_c = flag_counts.get("B", 0)
                m_c = flag_counts.get("M", 0)
                u_c = flag_counts.get("U", 0)
                print(f"    [FLAGS] P={p_c}, E={e_c}, B={b_c}, M={m_c}, U={u_c}")

    # Cross-source sanity checks: Tier-2 review notices, never fatal, reported
    # apart from the identity coverage; run once over the production tables that were scanned
    sanity = sanity_warnings(fresh_tables) if fresh_tables else []
    if sanity:
        print("\nSanity checks (cross-source; never fatal, not identities):")
    for w in sanity:
        m = match_warning(w, acks, w.dataset, as_of)
        if m is not None:
            matched_ack_indices.add(m.index)
        if m is not None and m.state in ("applies", "due"):
            print(f"    [ACKNOWLEDGED] {w.message} — {acks[m.index]['reason']}")
            if m.state == "due":
                due_acks.add(m.index)
            continue
        total_warnings += 1
        print(f"    [NOTICE] {w.message}")
        if m is not None and m.state == "expired":
            expired_acks.add(m.index)
        elif m is not None:
            print(f"    [CHANGED] sanity {w.series} {', '.join(w.periods)}: {m.detail}")

    # Freshness: reported on every run, never counted as a review notice
    freshness_failed = False
    if fresh_tables:
        try:
            schedule = load_update_schedule()
        except Exception as e:
            print(f"Error: Invalid update schedule: {e}")
            return 1
        statuses = freshness_status(fresh_tables, schedule, acks, as_of, production)
        print()
        for line in freshness_lines(statuses, as_of):
            print(line)
        matched_ack_indices.update(st.ack_index for st in statuses if st.ack_index is not None)
        # an overdue series whose acknowledgement has expired keeps that acknowledgement's index
        expired_acks.update(st.ack_index for st in statuses if st.state == "overdue" and st.ack_index is not None)
        freshness_failed = any(st.state in ("overdue", "unchecked") for st in statuses)

    # Acknowledgements past or near their review-by date
    if expired_acks or due_acks:
        print()
    for i in sorted(expired_acks):
        a = acks[i]
        print(f"    [EXPIRED] {a['check']} {ack_key(a)} ({', '.join(map(str, a.get('periods', [])))}): "
              f"review_by {a['review_by']} has passed; review it again — {a['reason']}")
    for i in sorted(due_acks - expired_acks):
        a = acks[i]
        print(f"    [DUE-FOR-REVIEW] {a['check']} {ack_key(a)} ({', '.join(map(str, a.get('periods', [])))}): "
              f"review_by {a['review_by']}")

    # Stale detection (all-datasets runs only)
    stale_acks = []
    if all_datasets:
        stale_acks = [ack for i, ack in enumerate(acks) if i not in matched_ack_indices]
        for sack in stale_acks:
            periods_str = ", ".join(map(str, sack.get("periods", [])))
            print(f"    [STALE] {ack_key(sack)} ({periods_str}): {sack['reason']}")

    print("\n" + "=" * 70)
    if all_passed:
        print(f"ALL CHECKS PASSED: {len(target_files)} dataset(s) verified ({total_obs:,} total observations, {total_warnings} review notice(s)).")
        if release:
            if total_warnings > 0 or (all_datasets and len(stale_acks) > 0) or expired_acks:
                return 1
            if freshness and freshness_failed:
                return 1
        return 0
    else:
        print("VALIDATION FAILED: Resolve the critical errors above before publishing.")
        return 1


def _events(periods: List[str]) -> List[List[str]]:
    """Split sorted periods into events: runs at most 3 periods (31 days for daily data) apart."""
    events: List[List[str]] = []
    for p in sorted(periods):
        if events:
            gap = period_span(events[-1][-1], p)
            if gap <= (31 if len(p) == 10 else 3):
                events[-1].append(p)
                continue
        events.append([p])
    return events


def propose_acknowledgements(warnings: List[Warning], acks: List[dict], as_of) -> List[dict]:
    """
    Draft acknowledgement entries for every warning no acknowledgement
    applies to: one entry per series (or sanity check), check and event, with the values filled
    in from the data, `reason` and `reviewer` empty, and review_by 12 months on. Warnings repeated
    in a seed snapshot are merged with the production table's.
    """
    as_of = pd.Timestamp(as_of).normalize()
    groups: Dict[Tuple[str, str], Dict[str, Any]] = {}
    for w in warnings:
        if w.check == "break":
            continue
        m = match_warning(w, acks, w.dataset, as_of)
        if m is not None and m.state in ("applies", "due"):
            continue
        g = groups.setdefault((w.series, w.check), {"periods": set(), "values": {}})
        g["periods"].update(str(p) for p in w.periods)
        g["values"].update(w.values or {})
    out = []
    for (key, check), g in sorted(groups.items()):
        for event in _events(sorted(g["periods"])):
            entry: Dict[str, Any] = {"sanity" if check == "sanity" else "series": key, "check": check,
                                     "periods": event}
            if check in VALUE_CHECKS:
                wanted = set(event)
                if check in ("jump", "scale_shift"):
                    # each jump also records the value before it
                    ordered = sorted(g["values"])
                    wanted |= {ordered[ordered.index(p) - 1] for p in event if p in ordered and ordered.index(p) > 0}
                # a sanity check also records the other side, keyed "<period> <series>"
                entry["values"] = {k: v for k, v in sorted(g["values"].items()) if k.split(" ")[0] in wanted}
            entry.update({"reason": "", "reviewer": "", "date": as_of.strftime("%Y-%m-%d"),
                          "review_by": (as_of + pd.DateOffset(months=REVIEW_MONTHS)).strftime("%Y-%m-%d")})
            out.append(entry)
    return out


PROPOSAL_HEADER = """\
# Draft acknowledgements (validate.py --propose-acknowledgements). Fill in reason and reviewer,
# set settled: true (review_by up to 5 years) for past events whose values are final, then
# copy the entries into pipeline/metadata/acknowledged_warnings.yaml.
"""


def collect_warnings(target_files: List[Path]) -> List[Warning]:
    """Every Tier-2 review warning of the target files, and the sanity checks (for --propose-acknowledgements)."""
    warnings: List[Warning] = []
    production = production_tables()
    frames: Dict[str, pd.DataFrame] = {}
    for f in target_files:
        df = pd.read_parquet(f) if f.suffix == ".parquet" else pd.read_csv(f)
        warnings += validate_tier2_details(df, dataset_name=f.name)[1]
        if f.stem in production:
            frames[f.stem] = df
    return warnings + sanity_warnings(frames)


def main():
    """Main CLI runner for dataset validation."""
    parser = argparse.ArgumentParser(description="iraqdata Pipeline Quality Gatekeeper")
    parser.add_argument("--release", action="store_true", help="Fail if any unacknowledged warning or stale entry")
    parser.add_argument("--list-acknowledged", action="store_true", help="Print acknowledged warnings as Markdown bullets and exit")
    parser.add_argument("--acknowledgements", type=str, default=str(ACKS_PATH), help="Path to acknowledgements YAML")
    parser.add_argument("--freshness", action="store_true",
                        help="With --release: also fail on any overdue or unchecked series (the release check)")
    parser.add_argument("--as-of", dest="as_of", default=None, metavar="YYYY-MM-DD",
                        help="Reference date for the freshness report (default: today)")
    parser.add_argument("--propose-acknowledgements", dest="propose", type=Path, default=None, metavar="FILE",
                        help="Write draft acknowledgements for every unacknowledged notice to FILE and exit "
                             "; acknowledged_warnings.yaml is not changed")
    parser.add_argument("files", nargs="*", help="Optional dataset files to validate")

    args = parser.parse_args()
    if args.as_of is None:
        as_of = today_utc()
    elif _is_date(args.as_of):
        as_of = pd.Timestamp(args.as_of)
    else:
        parser.error(f"--as-of must be a real date in YYYY-MM-DD form, not {args.as_of!r}")

    if args.list_acknowledged:
        try:
            acks = load_acknowledgements(args.acknowledgements)
        except Exception as e:
            print(f"Error loading acknowledgements: {e}")
            sys.exit(1)
        for ack in acks:
            periods_str = ", ".join(map(str, ack.get("periods", [])))
            print(f"- **{ack_key(ack)}** ({periods_str}): {ack['reason']} (reviewed by {ack['reviewer']} on {ack['date']}; "
                  f"review by {ack['review_by']})")
        sys.exit(0)

    try:
        acks = load_acknowledgements(args.acknowledgements)
    except Exception as e:
        print(f"Error: Invalid acknowledgements file: {e}")
        sys.exit(1)

    print("=" * 70)
    print("iraqdata Pipeline Quality Gatekeeper (Validation Suite)")
    print("=" * 70)

    is_all_datasets = (len(args.files) == 0)
    if not is_all_datasets:
        target_files = [Path(arg) for arg in args.files]
    else:
        # Default: scan pipeline/data/garden and pipeline/seeds
        garden_files = list((repo_root / "pipeline" / "data" / "garden").glob("*.parquet"))
        seed_files = list((repo_root / "pipeline" / "seeds").glob("*.parquet"))
        target_files = garden_files + seed_files

    if args.propose is not None:
        drafts = propose_acknowledgements(collect_warnings(target_files), acks, as_of)
        args.propose.parent.mkdir(parents=True, exist_ok=True)
        args.propose.write_text(
            PROPOSAL_HEADER + yaml.safe_dump({"acknowledged": drafts}, sort_keys=False, allow_unicode=True, width=100),
            encoding="utf-8")
        print(f"Wrote {len(drafts)} draft acknowledgement(s) to {args.propose}.")
        sys.exit(0)

    sys.exit(run_gatekeeper(target_files, acks, release=args.release, freshness=args.freshness,
                            as_of=as_of, all_datasets=is_all_datasets))


if __name__ == "__main__":
    main()
