"""
pipeline.validate
=================
Quality Gatekeeper for the iraqdata pipeline.

Executes:
- Tier 1 (Fatal Errors): Structural schema compliance (7 canonical columns, valid ISO
  dates, unique (date, series_id) keys, numeric dtypes, valid SDMX status flags).
- Tier 2 (Fatal Accounting Errors): Hard mathematical and macroeconomic identities
  (Budget balance & components, Nominal/Real GDP decompositions, BIS net position &
  sector liabilities, Broad money hierarchy, BOP trade balance,
  BOP exports/imports/current account decompositions, Currency outside banks <= M0 and M1).
- Tier 2 (Review Warnings): Economic plausibility envelopes, sign checks, period-on-period
  jump detection, x1000 scale-shift detection, and unfinished-period verification.

Configuration & Metadata:
- Rules: Declared in `pipeline/metadata/plausibility_rules.yaml` covering range, sign,
  unit, and jump thresholds for all published series.
- Acknowledgements: Genuine movements in the published source data are
  acknowledged in `pipeline/metadata/acknowledged_warnings.yaml` to allow clean release gates.
  Overdue series are acknowledged there too (`check: overdue`, `periods: [<latest period>]`).
- Update schedule: `pipeline/metadata/update_schedule.yaml` gives each series its source and
  expected publication lag, or marks it ended.

Output Lines:
- `[PASS]` / `[FAIL]`: Dataset verification summary
- `- <error>`: Fatal Tier 1 or Tier 2 accounting discrepancies
- `[NOTICE] <warning>`: Unacknowledged Tier 2 review notices
- `[INFO] <rule>: checked N period(s), skipped M (missing components)`: Identity coverage
- `[IDENTITY] <rule> (independent): checked N, skipped M`: Periods where every member is read from
  its own source, so the identity can fail
- `[IDENTITY] <rule> (definitional: <series>): N period(s), not a check`: Periods where <series> is
  computed from the other members (catalog origin `derived`), so the identity holds by
  definition; these are not evidence of consistency and are not counted as checked
- `[DERIVED] <series>: no independent identity check`: A published derived series that no
  independent identity covers; informational, never a notice
- `[COVERAGE] series: C checked, E exempt, U unchecked`: Plausibility envelope coverage
- `[FLAGS] P=p, E=e, B=b, M=m, U=u`: Status flag counts per dataset
- `[BREAK] <series> <period>: move xR at a B-flagged observation`: Expected breaks
- `[ACKNOWLEDGED] <warning> — <reason>`: Acknowledged review notices
- `[STALE] <acknowledgement>`: Stale acknowledgements that match no warnings
- `[GAP] <rule> <period>: <series> missing`: An identity period with some members missing
  (a review notice unless listed in `pipeline/metadata/expected_gaps.yaml`)
- `[GAP] <series>: no value for <periods> between <first> and <last>`: A monthly, quarterly or
  annual series with a period missing inside its range (a review notice unless the series is
  listed under `missing_periods` in `pipeline/metadata/expected_gaps.yaml`)
- `New Point Notice: <series> <period> moved ...`: One of a series' latest periods moved by many
  times its recent typical move (a robust z-score over the changes before it). Off until
  `enabled: true` in `pipeline/metadata/new_point_check.yaml`, whose header records the calibration
- `[SANITY] <check> <period>: ...`: A cross-source sanity check outside its band
  (`pipeline/metadata/sanity_checks.yaml`); a review notice, never fatal, not identity coverage
- `[EXPIRED] <check> <series> (<periods>)`: An acknowledgement past its `review_by`; its warnings
  are notices again and `--release` fails
- `[DUE-FOR-REVIEW] <check> <series> (<periods>)`: An acknowledgement within 30 days of `review_by`
- `[CHANGED] <check> <series> <periods>: acknowledged X, now Y`: A value an acknowledgement
  recorded was revised; the warning is a notice again
- Plausibility rules are `statistical` (generated by `pipeline/derive_rules.py`) or `reviewed`;
  jumps use a log change, or a change scaled by the rule's `scale` for series that can be zero
  or negative, so no observation pair is skipped for its sign.
- `[FRESHNESS] as of D: ...`: Freshness of every series in the production tables,
  followed by `[OVERDUE]`, `[ACKNOWLEDGED]`, `[ENDED]` and `[UNCHECKED-FRESHNESS]` lines. Never
  counted as a review notice; it fails a run only under `--release --freshness`.

Usage:
    python pipeline/validate.py
    python pipeline/validate.py --release                 # CI gate
    python pipeline/validate.py --release --freshness     # release check
    python pipeline/validate.py --as-of 2026-10-24        # freshness at a fixed date
    python pipeline/validate.py --list-acknowledged
    python pipeline/validate.py --propose-acknowledgements drafts.yaml
    python pipeline/validate.py --acknowledgements PATH
    python pipeline/validate.py path/to/dataset.parquet
"""

