def today_utc() -> pd.Timestamp:
    """Today's date in UTC, at midnight. CI and the weekly check run in UTC; a local date would differ near midnight."""
    return pd.Timestamp.now(tz="UTC").tz_localize(None).normalize()


def load_rules(path: Union[Path, str] = RULES_PATH) -> dict:
    """Load and cache plausibility rules from YAML."""
    path_obj = Path(path).resolve()
    key = str(path_obj)
    if key not in _RULES_CACHE:
        with open(path_obj, "r", encoding="utf-8") as f:
            rules = yaml.safe_load(f) or {}
        # Every limit is statistical or reviewed; history×3 is not allowed
        for sid, rule in (rules.get("series") or {}).items():
            if rule.get("exempt"):
                continue
            if rule.get("basis") not in RULE_BASES:
                raise ValueError(f"Invalid plausibility rule {sid}: basis {rule.get('basis')!r} not in {RULE_BASES}")
            if rule["basis"] == "reviewed" and not str(rule.get("rationale") or "").strip():
                raise ValueError(f"Invalid plausibility rule {sid}: a reviewed rule needs a rationale")
        _RULES_CACHE[key] = rules
    return _RULES_CACHE[key]


def load_acknowledgements(path: Union[Path, str] = ACKS_PATH) -> List[dict]:
    """
    Load and validate warning acknowledgements from YAML.
    Raises ValueError or returns list of dicts.
    """
    path_obj = Path(path).resolve()
    if not path_obj.exists():
        raise FileNotFoundError(f"Acknowledgements file not found: {path_obj}")
    with open(path_obj, "r", encoding="utf-8") as f:
        data = yaml.safe_load(f) or {}

    if not isinstance(data, dict) or "acknowledged" not in data:
        raise ValueError(f"Invalid acknowledgements file {path_obj}: missing 'acknowledged' list")

    acks = data.get("acknowledged")
    if not isinstance(acks, list):
        raise ValueError(f"Invalid acknowledgements file {path_obj}: 'acknowledged' must be a list")

    validated_acks = []
    for i, entry in enumerate(acks):
        if not isinstance(entry, dict):
            raise ValueError(f"Invalid acknowledgement #{i}: must be a dictionary")
        name = f"#{i} ({entry.get('series') or entry.get('sanity')} {entry.get('check')})"
        if bool(entry.get("series")) == bool(entry.get("sanity")):
            raise ValueError(f"Invalid acknowledgement {name}: give exactly one of 'series' or 'sanity'")
        for req in ["check", "periods", "reason", "reviewer", "date", "review_by"]:
            if req not in entry or (not entry[req] and req != "periods"):
                raise ValueError(f"Invalid acknowledgement {name}: missing or empty required field {req!r}")
        if entry["check"] not in VALID_CHECKS:
            raise ValueError(f"Invalid acknowledgement {name}: check {entry['check']!r} not in {VALID_CHECKS}")
        if (entry["check"] == "sanity") != bool(entry.get("sanity")):
            raise ValueError(f"Invalid acknowledgement {name}: a sanity check is acknowledged with 'sanity' and check: sanity")
        if not isinstance(entry["periods"], list):
            raise ValueError(f"Invalid acknowledgement {name}: 'periods' must be a list")
        entry["periods"] = [str(p) for p in entry["periods"]]
        for field in ("date", "review_by"):
            if not _DATE_RE.match(str(entry[field])):
                raise ValueError(f"Invalid acknowledgement {name}: {field!r} {entry[field]!r} must be YYYY-MM-DD")
            entry[field] = str(entry[field])
        # At most 12 months, or 5 years for settled history (a past event, final values)
        settled = entry.get("settled", False)
        if not isinstance(settled, bool):
            raise ValueError(f"Invalid acknowledgement {name}: 'settled' must be true or false")
        limit = pd.Timestamp(entry["date"]) + pd.DateOffset(years=REVIEW_YEARS_SETTLED if settled else 0,
                                                            months=0 if settled else REVIEW_MONTHS)
        if not pd.Timestamp(entry["date"]) < pd.Timestamp(entry["review_by"]) <= limit:
            raise ValueError(
                f"Invalid acknowledgement {name}: review_by {entry['review_by']} must be after date {entry['date']} "
                f"and at most {'5 years' if settled else '12 months'} later ({limit.strftime('%Y-%m-%d')})")
        # Tied to the acknowledged values
        if entry["check"] in VALUE_CHECKS:
            values = entry.get("values")
            if not isinstance(values, dict) or not values:
                raise ValueError(f"Invalid acknowledgement {name}: 'values' ({{period: value}}) is required for {entry['check']}")
            entry["values"] = {str(k): v for k, v in values.items()}
            missing = [p for p in entry["periods"] if p not in entry["values"]]
            if missing:
                raise ValueError(f"Invalid acknowledgement {name}: 'values' has no value for {missing}")
        validated_acks.append(entry)

    return validated_acks


def _yaml_list(path: Union[Path, str], key: str) -> List[dict]:
    path_obj = Path(path).resolve()
    with open(path_obj, "r", encoding="utf-8") as f:
        data = yaml.safe_load(f) or {}
    entries = data.get(key) if isinstance(data, dict) else None
    if not isinstance(entries, list):
        raise ValueError(f"Invalid {path_obj.name}: {key!r} must be a list")
    for i, entry in enumerate(entries):
        if not isinstance(entry, dict):
            raise ValueError(f"Invalid {path_obj.name} entry #{i}: must be a dictionary")
    return entries


def _require(entry: dict, fields, where: str) -> None:
    for req in fields:
        if req not in entry or entry[req] in (None, "", []):
            raise ValueError(f"Invalid {where}: missing or empty required field {req!r}")


def load_expected_gaps(path: Union[Path, str] = EXPECTED_GAPS_PATH) -> List[dict]:
    """Expected identity gaps: rule, period, missing (a list), reason."""
    entries = _yaml_list(path, "expected")
    for i, e in enumerate(entries):
        where = f"expected gap #{i} ({e.get('rule')} {e.get('period')})"
        _require(e, ("rule", "period", "missing", "reason"), where)
        if not isinstance(e["missing"], list):
            raise ValueError(f"Invalid {where}: 'missing' must be a list of series")
    return entries


def load_expected_missing(path: Union[Path, str] = EXPECTED_GAPS_PATH) -> Dict[str, dict]:
    """
    Series that lack periods inside their range by design: {series: {"periods": set or None, "reason"}}.
    An entry lists the missing `periods`, or says `sparse: true` (the series holds only some periods).
    """
    entries = _yaml_list(path, "missing_periods")
    out: Dict[str, dict] = {}
    for i, e in enumerate(entries):
        where = f"expected missing periods #{i} ({e.get('series')})"
        _require(e, ("series", "reason"), where)
        if bool(e.get("sparse")) == bool(e.get("periods")):
            raise ValueError(f"Invalid {where}: give either periods (a list) or sparse: true")
        if e["series"] in out:
            raise ValueError(f"Invalid {where}: listed twice")
        out[e["series"]] = {"periods": None if e.get("sparse") else {str(p) for p in e["periods"]}, "reason": e["reason"]}
    return out


_PERIOD_SHAPES = (("annual", re.compile(r"\d{4}$")), ("monthly", re.compile(r"\d{4}-\d{2}$")),
                  ("quarterly", re.compile(r"\d{4}-Q[1-4]$")))


def interior_gaps(df: pd.DataFrame) -> Dict[str, List[str]]:
    """
    {series: [periods with no value between its first and last]} for annual, monthly and quarterly
    series (daily ones have their own gap rule). A NaN value is no value.
    """
    out: Dict[str, List[str]] = {}
    have = df.dropna(subset=["value"]) if "value" in df.columns else df
    for sid, group in have.groupby("series_id"):
        dates = sorted({str(d) for d in group["date"]})
        shape = next((name for name, rx in _PERIOD_SHAPES if rx.match(dates[0])), None)
        if shape is None:
            continue
        if shape == "annual":
            full = [str(y) for y in range(int(dates[0]), int(dates[-1]) + 1)]
        else:
            freq = "M" if shape == "monthly" else "Q"
            span = pd.period_range(dates[0].replace("-Q", "Q"), dates[-1].replace("-Q", "Q"), freq=freq)
            full = [f"{p.year}-{p.month:02d}" if freq == "M" else f"{p.year}-Q{p.quarter}" for p in span]
        missing = sorted(set(full) - set(dates))
        if missing:
            out[str(sid)] = missing
    return out


def _runs(periods: List[str]) -> str:
    """'2013-02' or '2004-08 to 2005-07 (12 periods)', consecutive periods joined."""
    ordered, runs = sorted(periods), []
    index = {p: i for i, p in enumerate(ordered)}
    start = prev = None
    for p in ordered:
        nxt = prev is not None and _next_period(prev) == p
        if not nxt:
            if start is not None:
                runs.append((start, prev))
            start = p
        prev = p
    runs.append((start, prev))
    return ", ".join(a if a == b else f"{a} to {b}" for a, b in runs) + (f" ({len(index)} periods)" if len(index) > 1 else "")


def _next_period(p: str) -> str:
    if re.match(r"\d{4}$", p):
        return str(int(p) + 1)
    if "Q" in p:
        year, q = int(p[:4]), int(p[-1])
        return f"{year + (q == 4)}-Q{q % 4 + 1}"
    year, month = int(p[:4]), int(p[5:7])
    return f"{year + (month == 12)}-{month % 12 + 1:02d}"


def load_new_point_check(path: Union[Path, str] = NEW_POINT_PATH) -> dict:
    """The new-point volatility check's settings: enabled, k, latest, windows (see the file header)."""
    with open(path, "r", encoding="utf-8") as f:
        data = yaml.safe_load(f) or {}
    for field, kind in (("enabled", bool), ("k", (int, float)), ("latest", int), ("windows", dict)):
        value = data.get(field)
        if isinstance(value, bool) != (kind is bool) or not isinstance(value, kind):
            raise ValueError(f"Invalid {Path(path).name}: {field!r} must be a {getattr(kind, '__name__', 'number')}")
    if data["k"] <= 0 or data["latest"] < 1 or set(data["windows"]) != {"monthly", "quarterly"} \
            or any(not isinstance(w, int) or w < 6 for w in data["windows"].values()):
        raise ValueError(f"Invalid {Path(path).name}: k > 0, latest >= 1 and a window of at least 6 for monthly and quarterly")
    return data


def new_point_scores(values: np.ndarray, window: int) -> List[Tuple[int, float, float]]:
    """
    (index, z, change) for every point after the first `window` changes: z is the distance of its change from the
    median of the `window` changes before it, in units of their median absolute deviation (x 1.4826, floored at a
    quarter of their mean absolute deviation so a flat history makes no move infinite). The change is the log
    ratio of a positive series, otherwise the difference over the median absolute level.
    """
    values = np.asarray(values, dtype=float)
    if (values > 0).all():
        changes = np.diff(np.log(values))
    else:
        changes = np.diff(values) / (np.median(np.abs(values)) or 1.0)
    out = []
    for t in range(window, len(changes)):
        recent = changes[t - window:t]
        centre = np.median(recent)
        spread = max(np.median(np.abs(recent - centre)) * 1.4826, 0.25 * np.mean(np.abs(recent - centre)), 1e-12)
        out.append((t + 1, abs(changes[t] - centre) / spread, float(changes[t])))
    return out


def new_point_warnings(df: pd.DataFrame, dataset_name: str, config: dict) -> List["Warning"]:
    """Warnings for the latest `latest` periods of each monthly or quarterly series that moved more than k."""
    out: List[Warning] = []
    if not {"date", "series_id", "value"}.issubset(df.columns):
        return out
    flag_of = dict(zip(zip(df["series_id"], df["date"].astype(str)), df["status_flag"])) if "status_flag" in df.columns else {}
    for sid, group in df.dropna(subset=["value"]).groupby("series_id"):
        group = group.assign(date=group["date"].astype(str)).sort_values("date")
        dates = group["date"].tolist()
        shape = next((name for name, rx in _PERIOD_SHAPES if rx.match(dates[0])), None)
        window = config["windows"].get(shape)
        values = group["value"].to_numpy(dtype=float)
        if window is None or len(values) < window + 10:
            continue
        for index, z, change in new_point_scores(values, window):
            if index < len(values) - config["latest"] or z <= config["k"]:
                continue
            period, previous = dates[index], dates[index - 1]
            if flag_of.get((sid, period)) == "B" or flag_of.get((sid, previous)) == "B":
                continue  # a known break explains the move
            move = f"×{np.exp(change):.4g}" if (values > 0).all() else f"{change:+.4g} × median level"
            out.append(Warning(
                dataset=dataset_name, series=sid, check="new_point", periods=[period],
                message=(f"[{dataset_name}] New Point Notice: {sid} {period} moved {move} from {previous}, "
                         f"{z:.1f} times the recent typical move (limit {config['k']:g})"),
                values={previous: float(values[index - 1]), period: float(values[index])}))
    return out


SANITY_ALIGNS = ("same_period", "quarter_end_change")


def load_sanity_checks(path: Union[Path, str] = SANITY_CHECKS_PATH) -> List[dict]:
    """Cross-source sanity checks; see the file header for the fields."""
    entries = _yaml_list(path, "checks")
    for i, e in enumerate(entries):
        where = f"sanity check #{i} ({e.get('id')})"
        _require(e, ("id", "a", "b", "align", "rationale", "reviewed"), where)
        if e["align"] not in SANITY_ALIGNS:
            raise ValueError(f"Invalid {where}: align {e['align']!r} not in {SANITY_ALIGNS}")
        if e["align"] == "same_period":
            band = e.get("band")
            if not (isinstance(band, list) and len(band) == 2 and float(band[0]) < float(band[1])):
                raise ValueError(f"Invalid {where}: same_period needs band: [low, high]")
        else:
            tol = e.get("tolerance")
            if not (isinstance(tol, dict) and {"absolute", "relative"} <= set(tol)):
                raise ValueError(f"Invalid {where}: quarter_end_change needs tolerance: {{absolute, relative}}")
        if not _DATE_RE.match(str(e["reviewed"])):
            raise ValueError(f"Invalid {where}: reviewed {e['reviewed']!r} must be YYYY-MM-DD")
    ids = [e["id"] for e in entries]
    if len(ids) != len(set(ids)):
        raise ValueError("Invalid sanity_checks.yaml: repeated id")
    return entries


class Warning(NamedTuple):
    dataset: str
    series: str
    check: str
    periods: list
    message: str
    # {period: value} of the observations the warning is about (for a jump, also the previous
    # one); an acknowledgement is tied to them
    values: Optional[dict] = None


def ack_key(ack: dict) -> str:
    """The series, or the sanity check id, an acknowledgement is about."""
    return str(ack.get("series") or ack.get("sanity"))


def _same_value(a, b) -> bool:
    """Equal at 10 significant figures: absorbs floating-point noise only."""
    try:
        a, b = float(a), float(b)
    except (TypeError, ValueError):
        return False
    if np.isnan(a) or np.isnan(b):
        return bool(np.isnan(a) and np.isnan(b))
    return float(f"{a:.10g}") == float(f"{b:.10g}")


def _expired(ack: dict, as_of) -> bool:
    return "review_by" in ack and pd.Timestamp(as_of).normalize() > pd.Timestamp(ack["review_by"])


class AckMatch(NamedTuple):
    index: int
    state: str      # applies | due | expired | changed
    detail: str


def match_warning(w: Warning, acks: List[dict], dataset: Optional[str], as_of=None) -> Optional[AckMatch]:
    """
    The acknowledgement covering a warning, and its state. An acknowledgement covers a warning
    when its series (or sanity id), check and dataset (if given) match and every period of the
    warning is among its periods (one entry can cover an event's several periods).
    It applies unless review_by has passed (expired) or a value it records differs from the
    warning's value at 10 significant figures (changed). Within DUE_DAYS of review_by it still
    applies, as due. The first applying entry wins; otherwise the first failing one is returned.
    """
    as_of = today_utc() if as_of is None else pd.Timestamp(as_of).normalize()
    periods = {str(p) for p in w.periods}
    failed: Optional[AckMatch] = None
    for i, ack in enumerate(acks):
        if ack_key(ack) != w.series or ack.get("check") != w.check:
            continue
        if not periods <= {str(p) for p in ack.get("periods", [])}:
            continue
        ack_ds = ack.get("dataset")
        if ack_ds and ack_ds != (dataset if dataset is not None else w.dataset):
            continue
        if _expired(ack, as_of):
            failed = failed or AckMatch(i, "expired", f"review_by {ack['review_by']} has passed")
            continue
        stored = ack.get("values") or {}
        changed = [f"{p}: acknowledged {stored[p]:.10g}, now {v:.10g}" if p in stored else f"{p}: no acknowledged value, now {v:.10g}"
                   for p, v in (w.values or {}).items()
                   if w.check in VALUE_CHECKS and not (p in stored and _same_value(stored[p], v))]
        if changed:
            failed = failed or AckMatch(i, "changed", "; ".join(changed))
            continue
        due = "review_by" in ack and as_of >= pd.Timestamp(ack["review_by"]) - pd.Timedelta(days=DUE_DAYS)
        return AckMatch(i, "due" if due else "applies", "")
    return failed


def match_acknowledgements(
    warnings: List[Warning],
    acks: List[dict],
    dataset: Optional[str] = None,
    as_of=None,
) -> Tuple[List[Tuple[Warning, dict]], List[Warning], List[dict]]:
    """
    Match warnings against acknowledgements (match_warning). Returns (acknowledged,
    unacknowledged, stale): an expired or changed acknowledgement leaves its warning
    unacknowledged, but is not stale.
    """
    acknowledged: List[Tuple[Warning, dict]] = []
    unacknowledged: List[Warning] = []
    matched_acks = set()

    for w in warnings:
        m = match_warning(w, acks, dataset, as_of)
        if m is not None:
            matched_acks.add(m.index)
        if m is not None and m.state in ("applies", "due"):
            acknowledged.append((w, acks[m.index]))
        else:
            unacknowledged.append(w)

    stale = [ack for i, ack in enumerate(acks) if i not in matched_acks]
    return acknowledged, unacknowledged, stale


@functools.lru_cache(maxsize=None)
def period_end(date: str) -> pd.Timestamp:
    """
    Convert an ISO-like period string to its end-of-period Timestamp.
    - Daily ('YYYY-MM-DD'): that date
    - Monthly ('YYYY-MM'): end of month
    - Quarterly ('YYYY-Qn'): end of quarter
    - Annual ('YYYY'): 31 December
    """
    date_str = str(date).strip()
    if len(date_str) == 4 and date_str.isdigit():
        return pd.Timestamp(f"{date_str}-12-31")
    if "-Q" in date_str or "-q" in date_str:
        return pd.Period(date_str, freq="Q").end_time.floor("D")
    if len(date_str) == 7 and date_str[4] == "-":
        return pd.Period(date_str, freq="M").end_time.floor("D")
    return pd.Timestamp(date_str).floor("D")


def period_span(date1: str, date2: str) -> int:
    """Calculate the number of periods spanned between date1 and date2."""
    d1 = str(date1).strip()
    d2 = str(date2).strip()
    if len(d1) == 4 and d1.isdigit() and len(d2) == 4 and d2.isdigit():
        return int(d2) - int(d1)
    if ("-Q" in d1 or "-q" in d1) and ("-Q" in d2 or "-q" in d2):
        p1 = pd.Period(d1, freq="Q")
        p2 = pd.Period(d2, freq="Q")
        return (p2.year - p1.year) * 4 + (p2.quarter - p1.quarter)
    if len(d1) == 7 and d1[4] == "-" and len(d2) == 7 and d2[4] == "-":
        p1 = pd.Period(d1, freq="M")
        p2 = pd.Period(d2, freq="M")
        return (p2.year - p1.year) * 12 + (p2.month - p1.month)
    try:
        t1 = pd.Timestamp(d1)
        t2 = pd.Timestamp(d2)
        return (t2 - t1).days
    except Exception:
        return 1


def next_period(date: str) -> str:
    """The period after `date`, in the same format (daily, monthly, quarterly or annual)."""
    d = str(date).strip()
    if len(d) == 4 and d.isdigit():
        return str(int(d) + 1)
    if "-Q" in d or "-q" in d:
        p = pd.Period(d.upper(), freq="Q") + 1
        return f"{p.year}-Q{p.quarter}"
    if len(d) == 7 and d[4] == "-":
        return (pd.Period(d, freq="M") + 1).strftime("%Y-%m")
    return (pd.Timestamp(d) + pd.Timedelta(days=1)).strftime("%Y-%m-%d")


