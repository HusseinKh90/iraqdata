"""
pipeline.docs_cpi
=================
Keeps the numbers in docs/linked_inflation_method.md in step with the linked CPI.

    python pipeline/docs_cpi.py            # rewrite the generated block
    python pipeline/docs_cpi.py --check    # exit 1 if it is out of date

The block between `<!-- cpi-linking:begin -->` and `<!-- cpi-linking:end -->` holds every computed
number of the method doc: factors, splice months, continuity checks, the 2022 averages, the B
months and the post-splice year-on-year gaps. It is computed with pipeline/cpi_linking.py from the
published native base series only, so it cannot drift from the data and does not change when the
linked series is revised.
"""

import argparse
import sys
from pathlib import Path
from typing import Dict, List, Optional, Sequence

repo_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(repo_root / "pipeline"))

import pandas as pd  # noqa: E402

import cpi_linking  # noqa: E402

METHOD_DOC = repo_root / "docs" / "linked_inflation_method.md"
PRICES = repo_root / "pipeline" / "data" / "garden" / "prices_monthly.parquet"
BEGIN, END = "<!-- cpi-linking:begin -->", "<!-- cpi-linking:end -->"
KINDS = ("headline", "core")


def load_natives(path: Path = PRICES) -> Dict[str, Dict[str, pd.Series]]:
    """{kind: {series_id: native series}} from the published table (linked rows are ignored)."""
    df = pd.read_parquet(path, columns=["date", "series_id", "value"])
    out = {}
    for kind in KINDS:
        out[kind] = {}
        for base in cpi_linking.BASES:
            sid = f"cpi.{kind}_{base}"
            out[kind][sid] = df[df["series_id"] == sid].set_index("date")["value"].sort_index()
    return out


def _shift(date: str, months: int) -> str:
    y, m = map(int, date.split("-"))
    t = y * 12 + (m - 1) + months
    return f"{t // 12}-{t % 12 + 1:02d}"


def _pct(x: float) -> str:
    return f"{x:+.2f}%"


def render_block(natives: Optional[Dict[str, Dict[str, pd.Series]]] = None) -> str:
    natives = natives if natives is not None else load_natives()
    lines: List[str] = [BEGIN, "",
                        "_Generated by `pipeline/docs_cpi.py` from the published native series; do not edit by hand._", ""]

    lines += ["## 4. Factors and splices", "",
              "| Series | Old base | New base | Overlap year | Step factor | Chain factor to the 2022 base | Last month on old base | Splice month |",
              "|--------|----------|----------|--------------|-------------|-------------------------------|------------------------|--------------|"]
    for kind in KINDS:
        for s in cpi_linking.splices(natives[kind], kind):
            lines.append(f"| `cpi_{kind}` | {s.old_base} | {s.new_base} | {s.overlap_year} | {s.step_factor:.7g} | "
                         f"{s.chain_factor:.7g} | {s.last_old_month} | {s.splice_month} |")

    lines += ["", "## 5. Continuity checks", "",
              "Month-on-month change at each splice month, linked series against the new base, and the largest "
              "difference between the linked series and the old base over every month of the overlap year "
              "(month-on-month and year-on-year rates).", "",
              "| Series | Splice month | Linked MoM | New-base MoM | Largest overlap-year difference (pp) |",
              "|--------|--------------|------------|--------------|--------------------------------------|"]
    for kind in KINDS:
        n = natives[kind]
        linked = cpi_linking.link(n, kind)
        for s in cpi_linking.splices(n, kind):
            t, prev = s.splice_month, _shift(s.splice_month, -1)
            new = n[f"cpi.{kind}_{s.new_base}"]
            old = n[f"cpi.{kind}_{s.old_base}"]
            worst = 0.0
            for m in range(1, 13):
                d = f"{s.overlap_year}-{m:02d}"
                for lag in (1, 12):
                    u = _shift(d, -lag)
                    worst = max(worst, abs(linked[d] / linked[u] - old[d] / old[u]) * 100)
            lines.append(f"| `cpi_{kind}` | {t} | {_pct((linked[t] / linked[prev] - 1) * 100)} | "
                         f"{_pct((new[t] / new[prev] - 1) * 100)} | {worst:.2f} |")

    lines += ["", "## 6. Reference period", "",
              "The newest base is not rescaled, so the linked series is on the 2022 base's scale but its 2022 "
              "average is not exactly 100:", "",
              "| Series | Average over 2022 |", "|--------|-------------------|"]
    for kind in KINDS:
        lines.append(f"| `cpi_{kind}` | {cpi_linking.reference_average(natives[kind], kind):.3f} |")

    lines += ["", "## 7. Status flags", "",
              "| Series | Months flagged `B` (break) |", "|--------|----------------------------|"]
    for kind in KINDS:
        lines.append(f"| `cpi_{kind}` | {', '.join(cpi_linking.splice_months(natives[kind], kind))} |")

    lines += ["", "## 8. Post-splice year-on-year gaps", "",
              f"Linked year-on-year inflation against the new base's official rate for the 12 months from each "
              f"splice month. Gaps above the tolerance of {cpi_linking.TOLERANCE_PP} percentage points are "
              f"exceptions (see Limitations).", ""]
    for kind in KINDS:
        gaps = cpi_linking.post_splice_gaps(natives[kind], kind)
        lines += [f"`cpi_{kind}`: {int(gaps['exception'].sum())} of {len(gaps)} months above the tolerance.", "",
                  "| Month | Linked YoY | New-base YoY | Gap (pp) | Exception |",
                  "|-------|------------|--------------|----------|-----------|"]
        for row in gaps.itertuples():
            lines.append(f"| {row.date} | {_pct(row.linked_yoy)} | {_pct(row.official_yoy)} | {row.gap_pp:.2f} | "
                         f"{'yes' if row.exception else ''} |")
        lines.append("")
    lines += ["## 9. Sensitivity to the link month", "",
              "The new base divided by the old base is not constant through an overlap year: the two measure different "
              "baskets. The method uses December's ratio. Linking in another month would move **every level before "
              "the splice** (the percentages below apply to that pair; across several pairs they multiply).", "",
              "| Series | Old → new base | Overlap year | Ratio in January | Ratio in December (used) | Mean of the 12 ratios | "
              "Lowest | Highest | Link in January instead | Link at the mean instead |",
              "|--------|----------------|--------------|------------------|--------------------------|"
              "-----------------------|--------|---------|-------------------------|-------------------------|"]
    for kind in KINDS:
        for t in cpi_linking.link_sensitivity(natives[kind], kind):
            lines.append(f"| `cpi_{kind}` | {t.old_base} → {t.new_base} | {t.overlap_year} | {t.january:.6g} | "
                         f"{t.december:.6g} | {t.mean:.6g} | {t.lowest:.6g} | {t.highest:.6g} | "
                         f"{_pct(t.move(t.january))} | {_pct(t.move(t.mean))} |")
    lines.append("")
    lines.append(END)
    return "\n".join(lines)


def _replace_between(text: str, inner: str) -> str:
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise ValueError(f"{METHOD_DOC.name} must contain {BEGIN} and {END} exactly once")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + inner + tail


def wanted_bytes(path: Path = METHOD_DOC, natives=None) -> bytes:
    """The doc with a regenerated block; the file's own line endings are kept."""
    raw = path.read_bytes().decode("utf-8")
    crlf = "\r\n" in raw
    text = _replace_between(raw.replace("\r\n", "\n"), render_block(natives))
    return (text.replace("\n", "\r\n") if crlf else text).encode("utf-8")


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Generate or check the linked CPI method doc's numbers.")
    parser.add_argument("--check", action="store_true", help="exit 1 if the generated block is out of date")
    args = parser.parse_args(argv)
    wanted = wanted_bytes()
    if METHOD_DOC.read_bytes() == wanted:
        print("Linked CPI method doc is up to date.")
        return 0
    if args.check:
        print(f"Out of date: docs/{METHOD_DOC.name} (run python pipeline/docs_cpi.py)")
        return 1
    METHOD_DOC.write_bytes(wanted)
    print(f"Updated: {METHOD_DOC.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
