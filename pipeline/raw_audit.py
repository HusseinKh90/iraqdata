"""
pipeline.raw_audit
==================
Raw-layer audit: a committed manifest of every archived raw file, provenance resolution of
every published source_hash, the known-findings register, and an inventory of files no
parser reads.

    python pipeline/raw_audit.py manifest init [--force]
    python pipeline/raw_audit.py manifest add PATH [PATH ...]
    python pipeline/raw_audit.py manifest check
    python pipeline/raw_audit.py manifest backfill-held   # held_by for unknown dates
    python pipeline/raw_audit.py provenance
    python pipeline/raw_audit.py inventory
    python pipeline/raw_audit.py report

Raw files are judged by content hash only, never by modification time. The manifest is
append-only: a recorded hash is never rewritten.
"""

