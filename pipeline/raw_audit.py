MIN_PREFIX = 16


@dataclass
class ProvenanceResult:
    hash_cases: Dict[str, Tuple[str, Optional[str]]] = field(default_factory=dict)  # hash -> (case, target)
    row_counts: Counter = field(default_factory=Counter)                            # status -> rows
    group_errors: List[str] = field(default_factory=list)
    unregistered: List[Tuple[str, str, str, str, str]] = field(default_factory=list)
    stale: List[str] = field(default_factory=list)
    registered: Dict[str, int] = field(default_factory=dict)
    mirror_errors: List[str] = field(default_factory=list)
    total_rows: int = 0
    resolved_rows: int = 0
    registered_rows: int = 0

    @property
    def ok(self) -> bool:
        return not (self.group_errors or self.unregistered or self.stale or self.mirror_errors)


def production_table_names() -> List[str]:
    import run_parsers
    return sorted({Path(o).stem for spec in run_parsers.REGISTRY for o in spec.outputs})


def load_tables(directory: Path, names: Sequence[str]) -> Dict[str, pd.DataFrame]:
    return {name: pd.read_parquet(Path(directory) / f"{name}.parquet") for name in names}


def recompute_group(group: dict, root: Path = repo_root) -> str:
    """Recompute an input group's combined hash from its member files."""
    members = [Path(root) / m for m in group["members"]]
    method = group["method"]
    if method in ("concat_hexdigests_sorted", "concat_hexdigests_ordered"):
        digest = hashlib.sha256("".join(sha256_file(p) for p in members).encode("utf-8")).hexdigest()
    elif method == "concat_bytes_sorted_prefix16":
        hasher = hashlib.sha256()
        for p in members:
            hasher.update(p.read_bytes())
        digest = hasher.hexdigest()
    else:
        raise ValueError(f"Unknown input-group method {method!r} in group {group['name']}")
    return digest[:len(group["id"])]


def load_corrections(path: Path = CORRECTIONS_PATH) -> List[dict]:
    """Provenance corrections; [] when the file does not exist."""
    return load_yaml(path).get("corrections", []) if Path(path).exists() else []


def classify_hash(source_hash: str, files: List[dict], groups: Dict[str, dict],
                  corrections: Sequence[dict] = ()) -> Tuple[str, Optional[str]]:
    """
    Return (case, target): group, file, corrected, ambiguous or unresolved. A hash that resolves to
    nothing but that a provenance correction replaced is "corrected", with the target its
    corrected hash resolves to. A hash that names a real file stays "file", even if a correction
    re-attributed some rows that carried it (for example the JODI 2007 hash on later years' rows).
    """
    case, target = _classify_plain(source_hash, files, groups)
    if case != "unresolved":
        return case, target
    targets = {_classify_plain(c["corrected_hash"], files, groups)[1]
               for c in corrections if source_hash == c["published_hash"]}
    if len(targets) == 1:
        return "corrected", targets.pop()
    return case, target


def _classify_plain(source_hash: str, files: List[dict], groups: Dict[str, dict]) -> Tuple[str, Optional[str]]:
    if source_hash in groups:
        return "group", groups[source_hash]["name"]
    if len(source_hash) < MIN_PREFIX:
        return "unresolved", None
    matches = [e["path"] for e in files if e["sha256"].startswith(source_hash)]
    if len(matches) == 1:
        return "file", matches[0]
    if len(matches) > 1:
        return "ambiguous", None
    return "unresolved", None


def _register_entry_for(entries: List[dict], table: str, series_id: str, date: str, source_hash: str):
    for e in entries:
        if (e["table"] == table and series_id in e["series"]
                and str(e["from"]) <= date <= str(e["to"])
                and source_hash in (e["published_hash"], *e.get("hashes", []))):
            return e
    return None


def resolve_hashes(
    tables: Dict[str, pd.DataFrame],
    manifest: dict,
    findings: dict,
    seed_tables: Optional[Dict[str, pd.DataFrame]] = None,
    root: Path = repo_root,
) -> ProvenanceResult:
    """
    Resolve every distinct source_hash, check each production row's attribution against the
    parser registry, and compare the affected rows with the known-findings register.
    """
    import run_parsers

    run_parsers.clear_caches()
    result = ProvenanceResult()
    files = manifest.get("files", [])
    groups = {g["id"]: g for g in manifest.get("input_groups", [])}
    group_members = {g["name"]: set(g["members"]) for g in groups.values()}
    for g in groups.values():
        try:
            recomputed = recompute_group(g, root)
        except FileNotFoundError as exc:
            result.group_errors.append(f"{g['name']}: member missing ({exc})")
            continue
        if recomputed != g["id"]:
            result.group_errors.append(f"{g['name']}: recomputed {recomputed} != id {g['id']}")

    corrections = load_corrections()
    all_tables = list(tables.values()) + list((seed_tables or {}).values())
    for h in sorted({h for df in all_tables for h in df["source_hash"].unique()}):
        result.hash_cases[h] = classify_hash(h, files, groups, corrections)

    entries = findings.get("provenance", []) or []
    measured = Counter()
    expected_cache: Dict[Tuple[str, str, str], object] = {}

    for table, df in sorted(tables.items()):
        for series_id, date, source_hash in df[["series_id", "date", "source_hash"]].itertuples(index=False):
            result.total_rows += 1
            case, target = result.hash_cases[source_hash]
            key = (table, series_id, date)
            if key not in expected_cache:
                try:
                    expected_cache[key] = run_parsers.expected_inputs(table, series_id, date)
                except KeyError:
                    expected_cache[key] = KeyError
            expected = expected_cache[key]

            if case in ("unresolved", "ambiguous"):
                status = case
            elif expected is KeyError:
                status = "undeclared"
            elif expected is None:
                status = "unsourced"
            elif isinstance(expected, str):
                status = "attributed" if case == "group" and target == expected else "misattributed"
            else:
                # A corrected hash counts as the file its correction resolves to
                resolved = group_members.get(target, set()) if case == "group" else {target}
                # A tuple lists alternatives, any one of which may have produced the row (an unchanged row
                # keeps the hash of the source it was first published from)
                alternatives = expected if isinstance(expected, tuple) else (expected,)
                matched = False
                for files_used in alternatives:
                    # Any archived version of an expected file counts (after an update,
                    # unchanged rows keep the older version's fingerprint)
                    families = [run_parsers.versions_of(e) for e in files_used]
                    matched = matched or (all(any(r in fam for fam in families) for r in resolved)
                                          and all(fam & resolved for fam in families))
                status = "attributed" if matched else "misattributed"
            result.row_counts[status] += 1

            entry = _register_entry_for(entries, table, series_id, date, source_hash)
            if entry is not None:
                measured[entry["id"]] += 1
                result.registered_rows += 1
            elif status != "attributed":
                result.unregistered.append((table, series_id, date, source_hash, status))
            else:
                result.resolved_rows += 1

    for e in entries:
        result.registered[e["id"]] = measured.get(e["id"], 0)
        if measured.get(e["id"], 0) != e["count"]:
            result.stale.append(f"{e['id']}: register says {e['count']}, data has {measured.get(e['id'], 0)}")

    for snapshot, df_seed in sorted((seed_tables or {}).items()):
        table = run_parsers.SNAPSHOT_TABLE.get(snapshot)
        if table is None or table not in tables:
            continue
        if not df_seed.reset_index(drop=True).equals(tables[table].reset_index(drop=True)):
            result.mirror_errors.append(f"{snapshot} does not mirror {table}")
    return result


def run_provenance(manifest: Optional[dict] = None) -> ProvenanceResult:
    import run_parsers
    tables = load_tables(GARDEN_DIR, production_table_names())
    seeds = load_tables(SEEDS_DIR, sorted(run_parsers.SNAPSHOT_TABLE))
    return resolve_hashes(tables, manifest or load_manifest(), load_yaml(FINDINGS_PATH), seeds)


def print_provenance(res: ProvenanceResult) -> None:
    cases = Counter(case if case != "file" else f"file ({len(h)}-hex)" for h, (case, _) in res.hash_cases.items())
    print(f"Distinct published hashes: {len(res.hash_cases)}  "
          + ", ".join(f"{k}: {v}" for k, v in sorted(cases.items())))
    print("Rows by attribution: " + ", ".join(f"{k}: {v}" for k, v in sorted(res.row_counts.items())))
    share = 100.0 * res.registered_rows / res.total_rows if res.total_rows else 0.0
    print(f"Production observations: {res.total_rows:,}; traced to their source: {res.resolved_rows:,}; "
          f"in the known-findings register: {res.registered_rows:,} ({share:.1f}%)")
    for rid, n in res.registered.items():
        print(f"  {rid}: {n} observations")
    for msg in res.group_errors:
        print(f"GROUP ERROR   {msg}")
    for msg in res.mirror_errors:
        print(f"MIRROR ERROR  {msg}")
    for msg in res.stale:
        print(f"STALE ENTRY   {msg}")
    for table, series_id, date, h, status in res.unregistered[:50]:
        print(f"UNREGISTERED  {table} / {series_id} / {date}  hash {h}  ({status})")
    if len(res.unregistered) > 50:
        print(f"... and {len(res.unregistered) - 50} more unregistered rows")
    print(f"Provenance check: {'OK' if res.ok else 'FAILED'}")


