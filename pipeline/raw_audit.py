def _folder_rule(path: str):
    # The update check's workspace keeps raw files at <workdir>/raw/..., without "pipeline/"
    candidates = (path, f"pipeline/{path}")
    for prefix, origin, source_ref, acquired in FOLDER_RULES:
        if any(c.startswith(prefix) for c in candidates):
            return origin, source_ref, acquired
    return UNKNOWN, None, UNKNOWN


def load_source_ids(path: Path = SOURCES_PATH) -> set:
    """The ids of the terms-of-reuse records."""
    return {s["id"] for s in load_yaml(path).get("sources", [])} if Path(path).exists() else set()


def _is_date(value) -> bool:
    try:
        datetime.date.fromisoformat(str(value))
        return True
    except ValueError:
        return False


def _acquired_from_name(path: str) -> str:
    """Dated downloads carry their acquisition date in the file name."""
    stem = Path(path).stem
    tail = stem.rsplit("_", 1)[-1]
    if len(tail) == 10 and tail[4] == "-" and tail[7] == "-":
        return tail
    return UNKNOWN


def _consumers(path: str, consumers_map: Dict[str, list]) -> List[dict]:
    return [{"parser": name, "use": use} for name, use in consumers_map.get(path, [])]


def _status(consumers: List[dict]) -> str:
    return "parsed" if any(c["use"] == "parsed" for c in consumers) else "archived-not-parsed"


def file_entry(file_path: Path, root: Path = repo_root, consumers_map: Optional[Dict[str, list]] = None) -> dict:
    path = rel(file_path, root)
    if consumers_map is None:
        import run_parsers
        consumers_map = run_parsers.consumer_map()
    origin, source_ref, acquired = _folder_rule(path)
    if acquired is None:
        acquired = _acquired_from_name(path)
    consumers = _consumers(path, consumers_map)
    entry = {
        "path": path,
        "size": Path(file_path).stat().st_size,
        "sha256": sha256_file(file_path),
        "origin": origin,
        "acquired": acquired,
    }
    if acquired == UNKNOWN:
        # The file is provably held from the day it enters the manifest
        entry["held_by"] = datetime.datetime.now(datetime.timezone.utc).date().isoformat()
        entry["held_by_basis"] = "added to the manifest by raw_audit.py on this date"
    entry.update({"source_ref": source_ref, "consumers": consumers, "status": _status(consumers)})
    return entry


def build_manifest(root: Path = repo_root) -> dict:
    import run_parsers
    consumers_map = run_parsers.consumer_map()
    return {
        "files": [file_entry(p, root, consumers_map) for p in iter_raw_files(root)],
        "input_groups": [],
        "derived_snapshots": [{"path": path, "producer": producer} for path, producer in DERIVED_SNAPSHOTS.items()],
    }


def load_manifest(path: Path = MANIFEST_PATH) -> dict:
    return load_yaml(path)


def manifest_add(file_path: Path, manifest_path: Path = MANIFEST_PATH, root: Path = repo_root) -> bool:
    """
    Append a manifest entry for a file not yet listed. Returns True if an entry was added,
    False if the file is already listed with the same hash. Never rewrites a recorded hash.
    """
    manifest = load_manifest(manifest_path) if Path(manifest_path).exists() else {
        "files": [], "input_groups": [], "derived_snapshots": []}
    path = rel(file_path, root)
    for entry in manifest.get("files", []):
        if entry["path"] == path:
            current = sha256_file(file_path)
            if current != entry["sha256"]:
                raise ValueError(
                    f"{path} is already in the manifest with sha256 {entry['sha256']}, but the file "
                    f"now hashes to {current}. Raw files must never change; save new content under a new name."
                )
            return False
    entry = file_entry(file_path, root)
    if entry["source_ref"] is None:
        raise ValueError(
            f"{path} matches no source rule in raw_audit.FOLDER_RULES, so its source_ref (the terms of "
            "reuse in pipeline/metadata/sources.yaml) and acquired date are unknown. Add a rule, or name "
            "the file with its download date, before archiving it."
        )
    manifest.setdefault("files", []).append(entry)
    manifest["files"].sort(key=lambda e: e["path"])
    dump_yaml(manifest, Path(manifest_path), MANIFEST_HEADER)
    return True


INVENTORY_DOC = repo_root / "docs" / "source_inventory.md"


def _first_commit(path: str, root: Path = repo_root) -> Optional[Tuple[str, str]]:
    """(date, short hash) of the first commit that added `path`, or None outside git history."""
    proc = subprocess.run(["git", "log", "--diff-filter=A", "--follow", "--format=%ad %h", "--date=short", "--", path],
                          cwd=root, capture_output=True, text=True, encoding="utf-8")
    lines = proc.stdout.split()
    return (lines[-2], lines[-1]) if proc.returncode == 0 and len(lines) >= 2 else None


def held_by_evidence(path: str, inventory: str = "", root: Path = repo_root) -> Optional[Tuple[str, str]]:
    """
    (held_by, held_by_basis) for a file whose download date is unknown,
    from the earliest evidence: a dated statement naming the file in docs/source_inventory.md
    ("this copy dated 14 Oct 2026"), else the first commit that added it.
    """
    name = Path(path).name
    for line in inventory.splitlines():
        if name in line:
            m = re.search(r"this copy dated (\d{1,2} \w+ \d{4})", line)
            if m:
                day = datetime.datetime.strptime(m.group(1), "%d %b %Y").date().isoformat()
                return day, f"docs/source_inventory.md: \"this copy dated {m.group(1)}\""
    commit = _first_commit(path, root)
    if commit:
        return commit[0], f"first commit adding the path ({commit[1]})"
    return None


def backfill_held(manifest: dict, root: Path = repo_root) -> int:
    """Give every `acquired: unknown` entry without `held_by` its evidence; returns entries changed."""
    inventory = INVENTORY_DOC.read_text(encoding="utf-8") if INVENTORY_DOC.exists() else ""
    changed = 0
    for e in manifest.get("files", []):
        if e.get("acquired") != UNKNOWN or e.get("held_by"):
            continue
        found = held_by_evidence(e["path"], inventory, root)
        if found is None:
            continue
        rebuilt = {}
        for k, v in e.items():
            rebuilt[k] = v
            if k == "acquired":
                rebuilt["held_by"], rebuilt["held_by_basis"] = found
        e.clear()
        e.update(rebuilt)
        changed += 1
    return changed


def check_manifest(manifest: dict, root: Path = repo_root, source_ids: Optional[set] = None) -> List[Discrepancy]:
    """
    Compare the manifest with the files on disk, by content hash. Every entry also needs
    an acquisition date (a dated `acquired`, or `held_by` with `held_by_basis`) and a `source_ref`
    that names a record in pipeline/metadata/sources.yaml.
    """
    root = Path(root)
    source_ids = load_source_ids() if source_ids is None else source_ids
    listed = {e["path"]: e for e in manifest.get("files", [])}
    on_disk = {rel(p, root): p for p in iter_raw_files(root)}
    out: List[Discrepancy] = []
    for path, e in sorted(listed.items()):
        if not _is_date(e.get("acquired")) and not (_is_date(e.get("held_by")) and str(e.get("held_by_basis", "")).strip()):
            out.append(Discrepancy("undated", path, "no dated `acquired`, and no `held_by` with `held_by_basis`"))
        if e.get("source_ref") not in source_ids:
            out.append(Discrepancy("terms", path, f"source_ref {e.get('source_ref')!r} is not in sources.yaml"))
    for path in sorted(set(on_disk) - set(listed)):
        out.append(Discrepancy("unlisted", path, "file is not in the manifest"))
    for path in sorted(set(listed) - set(on_disk)):
        out.append(Discrepancy("missing", path, "manifest entry has no file"))
    for path in sorted(set(listed) & set(on_disk)):
        current = sha256_file(on_disk[path])
        if current != listed[path]["sha256"]:
            out.append(Discrepancy("changed", path, f"sha256 {listed[path]['sha256']} -> {current}"))
    return out


