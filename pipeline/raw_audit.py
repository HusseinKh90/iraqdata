def _cmd_manifest(args) -> int:
    if args.action == "init":
        if MANIFEST_PATH.exists() and not args.force:
            print(f"ERROR: {rel(MANIFEST_PATH)} exists. Use --force to rebuild it.", file=sys.stderr)
            return 1
        manifest = build_manifest()
        dump_yaml(manifest, MANIFEST_PATH, MANIFEST_HEADER)
        print(f"Wrote {rel(MANIFEST_PATH)}: {len(manifest['files'])} files, "
              f"{len(manifest['derived_snapshots'])} derived snapshots.")
        return 0
    if args.action == "add":
        if not args.paths:
            print("ERROR: manifest add needs at least one PATH.", file=sys.stderr)
            return 2
        try:
            for p in args.paths:
                added = manifest_add(Path(p).resolve())
                print(f"{'Added' if added else 'Already listed'}: {rel(Path(p).resolve())}")
        except ValueError as exc:
            print(f"ERROR: {exc}", file=sys.stderr)
            return 1
        return 0
    if args.action == "backfill-held":
        manifest = load_manifest()
        n = backfill_held(manifest)
        if n:
            dump_yaml(manifest, MANIFEST_PATH, MANIFEST_HEADER)
        print(f"held_by added to {n} entr{'y' if n == 1 else 'ies'}.")
        return 0
    # check
    problems = check_manifest(load_manifest())
    for d in problems:
        print(f"{d.kind.upper():9} {d.path}  ({d.detail})")
    print(f"Manifest check: {len(problems)} discrepancy(ies).")
    return 1 if problems else 0


def _cmd_provenance(args) -> int:
    res = run_provenance()
    print_provenance(res)
    return 0 if res.ok else 1


def _cmd_inventory(args) -> int:
    print_inventory(inventory(load_manifest()))
    return 0


def _section(title: str) -> None:
    print(f"\n{'=' * 70}\n{title}\n{'=' * 70}")


def _cmd_report(args) -> int:
    manifest = load_manifest()
    findings = load_yaml(FINDINGS_PATH)

    _section("1. Raw-file manifest")
    files = manifest.get("files", [])
    problems = check_manifest(manifest)
    print(f"Files: {len(files)} ({sum(e['size'] for e in files):,} bytes); "
          f"derived snapshots: {len(manifest.get('derived_snapshots', []))}; "
          f"input groups: {len(manifest.get('input_groups', []))}")
    for d in problems:
        print(f"{d.kind.upper():9} {d.path}  ({d.detail})")
    print(f"Manifest check: {len(problems)} discrepancy(ies).")

    _section("2. Fields still `unknown` (fill in from the publisher's documentation)")
    unknown = {e["path"]: [k for k in ("origin", "acquired") if e.get(k) == UNKNOWN] for e in files}
    unknown = {p: ks for p, ks in unknown.items() if ks}
    for field_name in ("origin", "acquired"):
        print(f"  {field_name}: {sum(field_name in ks for ks in unknown.values())} file(s)")
    held = {e["path"]: e.get("held_by") for e in files}
    for path, keys in unknown.items():
        note = f" (held by {held[path]})" if held.get(path) else ""
        print(f"  {path}: {', '.join(keys)}{note}")

    _section("3. Provenance of published observations")
    res = run_provenance(manifest)
    print_provenance(res)

    _section("4. Hand-checked values")
    print_hand_checks(load_yaml(HAND_CHECKS_PATH).get("values", []))

    _section("5. Parser robustness (known findings)")
    print_robustness(findings.get("robustness") or [])

    _section("6. Archived files no parser reads")
    items = inventory(manifest)
    for status, n in sorted(Counter(i["status"] for i in items).items()):
        print(f"  {status}: {n}")
    print_inventory(items)

    ok = not problems and res.ok
    print(f"\nRaw-layer audit: {'OK' if ok else 'FAILED'}")
    return 0 if ok else 1


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="iraqdata raw-layer audit")
    sub = parser.add_subparsers(dest="command", required=True)

    p_manifest = sub.add_parser("manifest", help="Create, extend or check the raw-file manifest")
    p_manifest.add_argument("action", choices=["init", "add", "check", "backfill-held"])
    p_manifest.add_argument("paths", nargs="*")
    p_manifest.add_argument("--force", action="store_true", help="init: rebuild an existing manifest")
    p_manifest.set_defaults(func=_cmd_manifest)

    p_prov = sub.add_parser("provenance", help="Trace every published source_hash")
    p_prov.set_defaults(func=_cmd_provenance)

    p_inv = sub.add_parser("inventory", help="List archived files no parser reads")
    p_inv.set_defaults(func=_cmd_inventory)

    p_report = sub.add_parser("report", help="Full raw-layer audit report")
    p_report.set_defaults(func=_cmd_report)
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    args = build_parser().parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
