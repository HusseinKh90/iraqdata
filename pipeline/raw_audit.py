def inventory(manifest: dict) -> List[dict]:
    """Manifest files that no parser parses, sorted by folder, with their status."""
    out = []
    for entry in manifest.get("files", []):
        consumers = entry.get("consumers") or []
        if any(c["use"] == "parsed" for c in consumers):
            continue
        hashed_by = [c["parser"] for c in consumers if c["use"] == "hashed-only"]
        out.append({
            "path": entry["path"],
            "folder": entry["path"].rsplit("/", 1)[0],
            "status": "superseded" if entry.get("status") == "superseded" else "archived-not-parsed",
            "size": entry["size"],
            "note": f"hashed only by {', '.join(hashed_by)}" if hashed_by else "",
        })
    return sorted(out, key=lambda e: (e["folder"], e["path"]))


def print_inventory(items: List[dict]) -> None:
    label = {"archived-not-parsed": "archived, not yet parsed", "superseded": "superseded"}
    folder = None
    for item in items:
        if item["folder"] != folder:
            folder = item["folder"]
            print(f"{folder}/")
        note = f" ({item['note']})" if item["note"] else ""
        print(f"  {item['path'].rsplit('/', 1)[1]}  {item['size']:,} bytes  {label[item['status']]}{note}")
    print(f"Files no parser reads: {len(items)}")


