def sha256_file(path: Path) -> str:
    """Full SHA-256 of a file as 64 lowercase hex characters."""
    hasher = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(65536):
            hasher.update(chunk)
    return hasher.hexdigest()


def rel(path: Path, root: Path = repo_root) -> str:
    """Repository-relative path with '/' separators, in Unicode NFC."""
    path = Path(path)
    if path.is_absolute():
        path = path.resolve().relative_to(Path(root).resolve())
    return unicodedata.normalize("NFC", path.as_posix())


def iter_raw_files(root: Path = repo_root) -> List[Path]:
    """Every raw file and seed input, sorted by manifest path. Derived snapshots are skipped."""
    root = Path(root)
    files = []
    for top in RAW_ROOTS:
        base = root / top
        if not base.exists():
            continue
        for p in base.rglob("*"):
            if p.is_file() and "__pycache__" not in p.parts and rel(p, root) not in DERIVED_SNAPSHOTS:
                files.append(p)
    return sorted(files, key=lambda p: rel(p, root))


def load_yaml(path: Path) -> dict:
    with open(path, "r", encoding="utf-8") as f:
        return yaml.safe_load(f) or {}


def dump_yaml(data: dict, path: Path, header: str = "") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    text = yaml.safe_dump(data, allow_unicode=True, sort_keys=False, width=1000)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(header + text)


