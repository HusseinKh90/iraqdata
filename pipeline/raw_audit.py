# Hand checks and robustness
# =====================================================================

def print_hand_checks(values: List[dict]) -> None:
    status = Counter(v["status"] for v in values)
    print(f"Hand-check values: {len(values)}  " + ", ".join(f"{k}: {n}" for k, n in sorted(status.items())))
    by_parser: Dict[str, List[str]] = {}
    for v in values:
        by_parser.setdefault(v["parser"], []).append(v["status"])
    compliant = sorted(p for p, s in by_parser.items() if all(x == "confirmed" for x in s))
    print(f"Parsers whose values are all confirmed: {len(compliant)} of {len(by_parser)}")
    pending = [v for v in values if v["status"] == "pending"]
    if pending:
        print("Pending: check each value against the published document, then set status: confirmed")
        for v in pending:
            t = v["target"]
            print(f"  {v['parser']:<20} {t['series']} {t['date']} = {v['expected']}  "
                  f"<- {v['source']} {v['locator']}")


def print_robustness(entries: List[dict]) -> None:
    if not entries:
        print("No open robustness findings")
        return
    counts = Counter((e["parser"], e["outcome"]) for e in entries)
    print(f"Robustness findings: {len(entries)}  "
          + ", ".join(f"{k}: {n}" for k, n in sorted(Counter(e['outcome'] for e in entries).items())))
    for parser in sorted({p for p, _ in counts}):
        parts = ", ".join(f"{o} {n}" for (p, o), n in sorted(counts.items()) if p == parser)
        print(f"  {parser:<20} {parts}")


