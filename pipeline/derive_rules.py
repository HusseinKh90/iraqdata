"""
pipeline.derive_rules
=====================
Evidence-based plausibility rules.

Every rule in `pipeline/metadata/plausibility_rules.yaml` has a basis:

- `statistical` (generated here): computed from the series' own published observations up to
  its `derived_through` date, as published then (vintages.as_of over the table and its history):
    - measure: `log` (|log(x_t / x_t-1)|) when every value is > 0, else `scaled`
      (|x_t - x_t-1| / scale, scale = median |x|), so no pair is skipped for its sign;
    - typical: the median of the non-zero changes;
    - jump threshold: K x typical (K = 10);
    - envelope: [min / 2, max x 2] for series > 0, else [min - range, max + range] (not below
      0 for a non_negative series).
  A series with fewer than MIN_OBSERVATIONS observations cannot be statistical.
- `reviewed`: a hand-set rule with a written `rationale`, never touched here.

The rules are frozen: new data never changes them, so a new erroneous value cannot widen the
limits that check it. Re-deriving is a deliberate step at rule review.

Usage:
    python pipeline/derive_rules.py --through YYYY-MM-DD   # re-derive every statistical rule
    python pipeline/derive_rules.py --check                # CI: rules equal a re-derivation
"""

import argparse
import re
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import numpy as np
import pandas as pd
import yaml

repo_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(repo_root / "src"))
sys.path.insert(0, str(repo_root / "pipeline"))

import vintages  # noqa: E402

RULES_PATH = repo_root / "pipeline" / "metadata" / "plausibility_rules.yaml"
GARDEN_DIR = repo_root / "pipeline" / "data" / "garden"
HISTORY_DIR = repo_root / "pipeline" / "data" / "history"

K = 10
MIN_OBSERVATIONS = 20
BASES = ("statistical", "reviewed")
KEY_ORDER = ("unit", "min", "max", "sign", "exempt", "jump", "basis", "rationale", "derived_through", "reviewed")
JUMP_ORDER = ("measure", "threshold", "typical", "k", "scale")

HEADER = """\
# Plausibility rules for every published series.
#
# Purpose: catch column shifts, wrong scales and moderate errors (a doubled CPI month, a misplaced
# decimal) before release. Every rule has a basis:
#   - statistical: generated by `python pipeline/derive_rules.py` from the series' own published
#     observations up to `derived_through`. jump.measure is log (|log(x_t/x_t-1)|,
#     every value > 0) or scaled (|x_t - x_t-1| / jump.scale, scale = median |x|); jump.typical
#     is the median non-zero change and jump.threshold = jump.k x typical (k = 10). The envelope
#     is [min/2, max x 2], or [min - range, max + range] for series that can be zero or negative.
#     Do not edit these by hand: `derive_rules.py --check` (run in CI) fails when a rule differs
#     from a re-derivation. New data never changes them; re-derive deliberately at rule review
#     with `derive_rules.py --through YYYY-MM-DD`.
#   - reviewed: a hand-set rule with a written rationale (too little history, or a known step
#     size). derive_rules.py never touches it.
# A real event a rule flags is acknowledged in acknowledged_warnings.yaml, never absorbed by a
# looser rule. Bounds are inclusive.
"""


# =====================================================================
# Derivation
# =====================================================================

def _sig(x: float) -> float:
    """Round to 6 significant figures, so the file is stable across platforms."""
    return float(f"{float(x):.6g}")


def published_values(through: str, garden: Path = GARDEN_DIR, history: Path = HISTORY_DIR) -> Dict[str, np.ndarray]:
    """{series_id: values sorted by date} as published on `through` (realtime_start <= through)."""
    out: Dict[str, np.ndarray] = {}
    for path in sorted(Path(garden).glob("*.parquet")):
        table = pd.read_parquet(path)
        hist_path = Path(history) / path.name
        hist = pd.read_parquet(hist_path) if hist_path.exists() else None
        df = vintages.as_of(table, hist, through).dropna(subset=["value"])
        for sid, g in df.groupby("series_id"):
            out[sid] = g.sort_values("date", kind="mergesort")["value"].to_numpy(dtype=float)
    return out


def derive(values: np.ndarray, sign: str) -> Tuple[Dict, float, float]:
    """(jump, min, max) for a series' values. Raises ValueError when it cannot."""
    if len(values) < MIN_OBSERVATIONS:
        raise ValueError(f"{len(values)} observations; a statistical rule needs at least {MIN_OBSERVATIONS}")
    positive = bool((values > 0).all())
    if positive:
        changes = np.abs(np.diff(np.log(values)))
        jump = {"measure": "log"}
    else:
        scale = float(np.median(np.abs(values)))
        if scale == 0:
            raise ValueError("median |value| is 0; no scale for a scaled change")
        changes = np.abs(np.diff(values)) / scale
        jump = {"measure": "scaled"}
    nonzero = changes[changes > 0]
    if len(nonzero) == 0:
        raise ValueError("the series never changes; no typical change")
    typical = float(np.median(nonzero))
    jump.update({"threshold": _sig(K * typical), "typical": _sig(typical), "k": K})
    if not positive:
        jump["scale"] = _sig(scale)
    lo, hi = float(values.min()), float(values.max())
    if positive:
        env_min, env_max = lo / 2, hi * 2
    else:
        span = hi - lo
        env_min, env_max = lo - span, hi + span
        if sign in ("non_negative", "positive"):
            env_min = max(env_min, 0.0)
    return jump, _sig(env_min), _sig(env_max)


def statistical_rule(rule: dict, values: Optional[np.ndarray], through: str, sid: str) -> dict:
    if values is None:
        raise ValueError(f"{sid}: no published observations; give it basis: reviewed with a rationale")
    try:
        jump, env_min, env_max = derive(values, rule.get("sign", "any"))
    except ValueError as exc:
        raise ValueError(f"{sid}: {exc}; give it basis: reviewed with a rationale") from None
    new = {k: v for k, v in rule.items() if k in ("unit", "sign")}
    new.update({"min": env_min, "max": env_max, "jump": jump, "basis": "statistical",
                "derived_through": through, "reviewed": rule.get("reviewed", through)})
    return new


def rederive(rules: dict, values_at, through: Optional[str] = None) -> dict:
    """
    The rules with every statistical rule re-derived: at `through` (a new derivation), or at its
    own `derived_through` (a check). `values_at(date)` gives {series_id: values}.
    """
    out = {"defaults": rules.get("defaults", {}), "series": {}}
    cache: Dict[str, Dict[str, np.ndarray]] = {}
    for sid, rule in rules["series"].items():
        if rule.get("basis") == "reviewed" or rule.get("exempt"):
            out["series"][sid] = rule
            continue
        at = through or str(rule.get("derived_through") or "")
        if not at:
            raise ValueError(f"{sid}: basis {rule.get('basis')!r} has no derived_through; run --through first")
        if at not in cache:
            cache[at] = values_at(at)
        new = statistical_rule(rule, cache[at].get(sid), at, sid)
        if through:
            new["reviewed"] = through
        out["series"][sid] = new
    return out


def problems(rules: dict) -> List[str]:
    """Rule errors independent of the data: bases, rationales and required fields."""
    errs = []
    for sid, rule in rules["series"].items():
        if rule.get("exempt"):
            continue
        basis = rule.get("basis")
        if basis not in BASES:
            errs.append(f"{sid}: basis {basis!r} is not one of {BASES} (history×3 is not allowed)")
            continue
        if basis == "reviewed" and not str(rule.get("rationale") or "").strip():
            errs.append(f"{sid}: a reviewed rule needs a rationale")
        if not re.match(r"^\d{4}-\d{2}-\d{2}$", str(rule.get("reviewed", ""))):
            errs.append(f"{sid}: reviewed must be YYYY-MM-DD")
        jump = rule.get("jump") or {}
        if jump.get("measure") not in ("log", "scaled"):
            errs.append(f"{sid}: jump.measure must be log or scaled")
        if jump.get("measure") == "scaled" and not jump.get("scale"):
            errs.append(f"{sid}: a scaled jump needs jump.scale")
    return errs


# =====================================================================
# The rules file
# =====================================================================

def _scalar(v) -> str:
    return yaml.safe_dump(v, allow_unicode=True, default_flow_style=True, width=10_000).strip().removesuffix("...").strip()


def _groups(path: Path) -> Dict[str, str]:
    """{series_id: its '# --- <table>' group comment} from the current file."""
    groups, current = {}, ""
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        m = re.match(r"^  # --- (.+)$", line)
        if m:
            current = m.group(1).strip()
            continue
        m = re.match(r"^  ([^\s#:][^:]*):\s*$", line)
        if m:
            groups[m.group(1)] = current
    return groups


def render(rules: dict, groups: Dict[str, str]) -> str:
    lines = [HEADER.rstrip("\n"), "", "defaults:"]
    for k, v in rules["defaults"].items():
        lines.append(f"  {k}: {_scalar(v)}")
    lines += ["", "series:"]
    last = None
    for sid, rule in rules["series"].items():
        group = groups.get(sid, "")
        if group != last:
            lines.append(f"  # --- {group}")
            last = group
        lines.append(f"  {sid}:")
        keys = [k for k in KEY_ORDER if k in rule] + [k for k in rule if k not in KEY_ORDER]
        for k in keys:
            v = rule[k]
            if k == "jump":
                parts = [f"{j}: {_scalar(v[j])}" for j in JUMP_ORDER if j in v]
                parts += [f"{j}: {_scalar(x)}" for j, x in v.items() if j not in JUMP_ORDER]
                lines.append(f"    jump: {{{', '.join(parts)}}}")
            else:
                lines.append(f"    {k}: {_scalar(str(v) if k in ('reviewed', 'derived_through') else v)}")
    return "\n".join(lines) + "\n"


def load(path: Path = RULES_PATH) -> dict:
    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f)


def _defaults(rules: dict) -> dict:
    keep = {k: v for k, v in rules.get("defaults", {}).items() if k.startswith("scale_shift")}
    return {"k": K, "min_observations": MIN_OBSERVATIONS, **keep}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Derive or check the statistical plausibility rules.")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--through", metavar="YYYY-MM-DD", help="Re-derive every statistical rule from data published by this date.")
    mode.add_argument("--check", action="store_true", help="Exit 1 if any rule differs from a re-derivation at its derived_through.")
    parser.add_argument("--rules", type=Path, default=RULES_PATH)
    parser.add_argument("--garden", type=Path, default=GARDEN_DIR)
    parser.add_argument("--history", type=Path, default=HISTORY_DIR)
    args = parser.parse_args(argv)

    rules = load(args.rules)
    rules["defaults"] = _defaults(rules)

    def values_at(date):
        return published_values(date, args.garden, args.history)

    if args.check:
        errs = problems(rules)
        try:
            fresh = rederive(rules, values_at)
        except ValueError as exc:
            errs.append(str(exc))
            fresh = None
        if fresh is not None:
            for sid, rule in rules["series"].items():
                if fresh["series"][sid] != rule:
                    errs.append(f"{sid}: differs from a re-derivation at {rule.get('derived_through')}: "
                                f"file {rule} vs derived {fresh['series'][sid]}")
        for e in errs:
            print(f"[RULES] {e}")
        print(f"{len(errs)} problem(s) in {len(rules['series'])} rule(s).")
        return 1 if errs else 0

    if not re.match(r"^\d{4}-\d{2}-\d{2}$", args.through):
        parser.error("--through takes YYYY-MM-DD")
    try:
        fresh = rederive(rules, values_at, args.through)
    except ValueError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    bad = problems(fresh)
    if bad:
        for e in bad:
            print(f"ERROR: {e}", file=sys.stderr)
        return 1
    changed = [sid for sid in fresh["series"] if fresh["series"][sid] != rules["series"].get(sid)]
    args.rules.write_text(render(fresh, _groups(args.rules)), encoding="utf-8", newline="\n")
    print(f"Derived {sum(r.get('basis') == 'statistical' for r in fresh['series'].values())} statistical rule(s) "
          f"through {args.through}; {len(changed)} changed: {', '.join(changed) or 'none'}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
